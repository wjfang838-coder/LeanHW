#!/usr/bin/env python3
"""Stage 3 — formal diagnosis, and the certificates that keep it honest.

The four queries of `goal.md` are run *inside Lean*, over the case's own domain:

    Difference   -> ambiguity        two readings admit different sets at some legal context
    Freedom      -> incompleteness   one context admits more than one observation
    Deadness     -> contradiction    one legal context admits nothing
    Equivalence  -> redundancy       two readings agree over the whole domain: merge them

One refinement of the first row, which `goal.md`'s table leaves implicit.  When a spec
contradicts itself, the readings that repair it (each dropping a different offending clause)
also differ from the unrepaired one -- so a naive count reports the same contradiction once as
`contradiction` and again as one `ambiguity` per repair.  `emitDifference` therefore reports
whether each side is dead somewhere, and a separation involving a dead side is counted as a
`repair_option`, not as an ambiguity.  An ambiguity is a disagreement between two readings the
prose can *both* satisfy.

Everything here is generated.  `Diagnose.lean` is written from `extraction.json` (which
choices exist, which tags each has) plus the case's `Partial.lean`; `Certificates.lean` is
written from what `Diagnose.lean` *found*, one theorem per finding, stated about the same
context term the search returned.

That two-pass shape is the point.  A hand-written certificate can quietly be about a
different input than the one reported -- `harness/clarify.py` documents exactly that failure
("the theorem says these two readings disagree on THIS input, and says nothing at all if the
two sides are given different inputs").  Here the theorem's subject is `ctx_lean` from the
search's own output, so the reported witness and the proved witness are the same term by
construction.

A finding whose certificate does not close, or closes with `sorryAx` in its axioms, is
downgraded to `uncertified` and is reported that way rather than dropped: a diagnosis the
machine could not confirm is a fact about this pipeline, and hiding it would make the
certified count meaningless.
"""
from __future__ import annotations

import json
import os
import re

from . import cases, leanrun, schema

# Wall-clock budgets for the two certificate attempts.  They are deliberately lopsided: the
# `decide` attempt is a probe -- cheap when it works, and worth abandoning early when it does not,
# because the escalation below is strictly more capable and, measured on a C(8,2) menu, better
# than five times faster.  The kernel attempt is the one that has to succeed, so it gets the room.
CERT_DECIDE_S = 300
CERT_KERNEL_S = 2400

HEADER = """\
-- GENERATED by leanspec/{who}.py -- do not edit.
-- Source of truth: extraction.json (which forks exist) and Partial.lean (what they mean).
import Partial
open LeanSpec

set_option maxRecDepth 100000
set_option maxHeartbeats 4000000
"""


def _cfg_defs(ext: dict) -> list[str]:
    """One `Cfg` per candidate reading, and one per hole-pinned probe."""
    out = []
    for k in ext["choices"]:
        for c in k["candidates"]:
            out.append(f"def cfg_{k['name']}_{c['tag']} : Cfg := "
                       f"{{ defaultCfg with c_{k['name']} := K{k['name']}.{c['tag']} }}")
    return out


def gen_diagnose(ext: dict, partial_src: str = "") -> str:
    L = [HEADER.format(who="diagnose"), ""]
    L += _cfg_defs(ext) + [""]
    L += ["-- The domain every finding below is relative to.",
          "#eval emitDomain case", ""]
    for k in ext["choices"]:
        name, tags = k["name"], [c["tag"] for c in k["candidates"]]
        L.append(f"-- choice `{name}`: {' vs '.join(tags)}")
        for i in range(len(tags)):
            for j in range(i + 1, len(tags)):
                a, b = tags[i], tags[j]
                L.append(f'#eval emitDifference case "{name}" "{a}" "{b}" '
                         f"(admits cfg_{name}_{a}) (admits cfg_{name}_{b})")
                L.append(f'#eval emitEquivalence case "{name}" "{a}" "{b}" '
                         f"(admits cfg_{name}_{a}) (admits cfg_{name}_{b})")
        if len(tags) > 2:
            cands = ", ".join(f'("{t}", admits cfg_{name}_{t})' for t in tags)
            L.append(f'#eval emitSplit case "{name}" [{cands}]')
        L.append("")
    L += ["-- incompleteness: the default reading, with every hole still open",
          '#eval emitFreedom case "default" (admits defaultCfg)']
    for h in ext["holes"]:
        # With the value domain in hand the search can look for a context that *answers* the
        # hole rather than one that merely proves it open; without it, the cheapest free
        # context is all there is to ask for.
        pins = (f" (cfgPins_{h['name']}.map (fun p => (p.1, admits p.2)))"
                if re.search(rf"(?m)^\s*def\s+cfgPins_{re.escape(h['name'])}\b", partial_src)
                else "")
        L.append(f'#eval emitHole case "{h["name"]}" (admits defaultCfg) '
                 f"(admits cfgPin_{h['name']}){pins}")
    L += ["", "-- contradiction", '#eval emitDeadness case "default" (admits defaultCfg)', ""]
    return "\n".join(L) + "\n"


def _lean_term(t: str) -> str:
    return f"({t})"


def gen_certificates(ext: dict, findings: list[dict],
                     partial_src: str = "", kernel: bool = False) -> tuple[str, dict]:
    """A theorem per finding, stated about the context the search returned.

    Returns the source and a map `theorem name -> the finding it certifies`, so a failed or
    admitted proof can be attributed back to the claim it was supposed to support.

    `kernel` swaps every `decide` for `decide +kernel`.  It proves the same propositions --
    the difference is which evaluator reduces them, not what is claimed -- and it is the
    fallback `diagnose` reaches for when the elaborator's evaluation overflows the stack on a
    large domain, or times out on a long one.  It is a parameter and not the default because
    plain `decide` gives a better error when a claim is simply false, and most cases never
    need the other.
    """
    L = [HEADER.format(who="diagnose"), ""]
    L += _cfg_defs(ext) + [""]
    owner: dict[str, dict] = {}

    def add(thm: str, stmt: str, tac: str, f: dict) -> None:
        if kernel and tac == "decide":
            tac = "decide +kernel"
        L.append(f"theorem {thm} :\n    {stmt} := by {tac}")
        L.append(f"#print axioms {thm}")
        owner[thm] = f

    for f in findings:
        q = f.get("query")
        if q == "difference" and f.get("separated"):
            n, a, b = f["choice"], f["a"], f["b"]
            c = _lean_term(f["ctx_lean"])
            add(f"legal_{n}_{a}_{b}", f"legal {c} = true", "decide", f)
            add(f"diff_{n}_{a}_{b}",
                f"admitSet (admits cfg_{n}_{a}) obsUniverse {c}\n      ≠ "
                f"admitSet (admits cfg_{n}_{b}) obsUniverse {c}", "decide", f)
            if f.get("discriminating"):
                # The stronger claim, and the one that makes the oracle query worth asking:
                # nothing is admitted by both, so any observation here refutes a reading.
                add(f"disj_{n}_{a}_{b}",
                    f"disjointAt (admits cfg_{n}_{a}) (admits cfg_{n}_{b}) obsUniverse {c}\n"
                    f"      = true", "decide", f)
        elif q == "equivalence" and f.get("equivalent"):
            n, a, b = f["choice"], f["a"], f["b"]
            add(f"equiv_{n}_{a}_{b}",
                f"queryEquivalence (admits cfg_{n}_{a}) (admits cfg_{n}_{b})\n"
                f"      obsUniverse ctxUniverse legal = true", "decide +kernel", f)
        elif q == "hole" and f.get("free"):
            n, c = f["hole"], _lean_term(f["ctx_lean"])
            add(f"legal_hole_{n}", f"legal {c} = true", "decide", f)
            add(f"free_{n}",
                f"1 < (admitSet (admits defaultCfg) obsUniverse {c}).length", "decide", f)
            add(f"attrib_{n}",
                f"admitSet (admits defaultCfg) obsUniverse {c}\n      ≠ "
                f"admitSet (admits cfgPin_{n}) obsUniverse {c}", "decide", f)
            if f.get("pinning"):
                add(f"pin_{n}",
                    f"pinningAt (cfgPins_{n}.map (fun p => admits p.2)) obsUniverse {c}\n"
                    f"      = true", "decide", f)
        elif q == "deadness" and f.get("dead"):
            c = _lean_term(f["ctx_lean"])
            add("legal_dead", f"legal {c} = true", "decide", f)
            add("dead_default",
                f"admitSet (admits defaultCfg) obsUniverse {c} = []", "decide", f)

    # Predictions, recorded before the oracle is asked.  Emitted from the same file as the
    # certificates so a prediction cannot be regenerated after the answer is known without
    # the certificate's timestamp moving with it.
    L.append("")
    for f in findings:
        if f.get("query") == "difference" and f.get("separated"):
            n, a, b, c = f["choice"], f["a"], f["b"], _lean_term(f["ctx_lean"])
            L.append(f'#eval emitPredict case "{n}:{a}" (admits cfg_{n}_{a}) {c}')
            L.append(f'#eval emitPredict case "{n}:{b}" (admits cfg_{n}_{b}) {c}')
        elif f.get("query") == "hole" and f.get("free"):
            n, c = f["hole"], _lean_term(f["ctx_lean"])
            L.append(f'#eval emitPredict case "hole:{n}" (admits defaultCfg) {c}')
            # If the case enumerated the hole's value domain, predict per value: without that
            # the oracle can only confirm the hole is free, never say what fills it.
            if re.search(rf"(?m)^\s*def\s+cfgPins_{re.escape(n)}\b", partial_src):
                L.append(f'#eval emitPredictEach case "hole:{n}" '
                         f"(cfgPins_{n}.map (fun p => (p.1, admits p.2))) {c}")
    return "\n".join(L) + "\n", owner


def diagnose(case: cases.Case) -> dict:
    """Run stage 3 for one case and write `diagnosis.json`."""
    ext = json.load(open(case.path("extraction.json")))
    partial_src = open(case.path("sandbox", "Partial.lean"), errors="replace").read()

    structural = schema.check_partial(partial_src, ext)
    for h in ext["holes"]:
        if not re.search(rf"(?m)^\s*def\s+cfgPin_{re.escape(h['name'])}\b", partial_src):
            structural.append(f"Partial.lean: hole `{h['name']}` has no `cfgPin_{h['name']}` "
                              f"-- without a pinned probe the freedom cannot be attributed to it")
    if structural:
        return {"case": case.name, "stage": "diagnose", "ok": False,
                "structural_errors": structural}

    # Recompile the case's own semantics first: `Diagnose.lean` imports `Partial`, and a stale
    # olean would diagnose the previous round's specification while reporting this round's.
    pres = leanrun.run(case.path("sandbox", "Partial.lean"), emit_olean=True)
    if not pres["ok"]:
        return {"case": case.name, "stage": "diagnose", "ok": False,
                "lean": leanrun.summarize(pres), "errors": pres["errors"][:20],
                "admitted": pres["admitted"]}

    dpath = case.path("sandbox", "Diagnose.lean")
    open(dpath, "w").write(gen_diagnose(ext, partial_src))
    res = leanrun.run(dpath)
    open(case.path("diagnose.log"), "w").write(res["log"])
    if not res["ok"]:
        return {"case": case.name, "stage": "diagnose", "ok": False,
                "lean": leanrun.summarize(res), "errors": res["errors"][:20],
                "admitted": res["admitted"]}

    findings = res["findings"]
    cpath = case.path("sandbox", "Certificates.lean")
    src, owner = gen_certificates(ext, findings, partial_src)
    open(cpath, "w").write(src)
    # A short leash on the first attempt, a long one on the escalation below.  Plain `decide` is
    # the FAST path or it is the wrong path: on the domains where it works at all it finishes in
    # a minute or two, and once it is grinding, waiting is not what fixes it -- the kernel is.
    cres = leanrun.run(cpath, timeout=CERT_DECIDE_S)

    # `decide` evaluates in the ELABORATOR, and the elaborator's evaluator is the wrong tool for
    # a large fold in three distinct ways.  Its recursion is bounded by the C stack, so a
    # certificate that scans `obsUniverse` at a domain of a few hundred observations can exhaust
    # it -- the process aborts and every theorem in the file, including the ones already proved,
    # comes back with no `#print axioms` line at all.  Its reduction is bounded by
    # `maxHeartbeats`, so a certificate whose contexts are long rather than numerous times out at
    # `isDefEq` -- the file elaborates to the end, every `#print axioms` line is printed, and the
    # theorems that timed out are *admitted*, resting on `sorryAx`.  And it is simply SLOW, by a
    # factor this file measured at better than five, so a menu wide enough to need C(n,2) triples
    # can run out of the wall clock with a prefix of its theorems proved and the rest never
    # reached -- `exit=124`, a partial axiom roster, and not one `sorryAx` among it.  Three
    # symptoms, one cause, one remedy: `decide +kernel` states the same proposition and hands the
    # evaluation to the kernel, which neither recurses on the C stack nor counts heartbeats, and
    # which evaluates the fold outright instead of unfolding it through whnf.
    #
    # So the tactic is not a property of the claim, it is a property of how big the domain got,
    # and picking it up front would mean guessing.  Retry instead: if the file did not elaborate
    # cleanly, and the reason is any of the three symptoms, re-emit it with `+kernel` and run it
    # again.  A case whose plain `decide` already worked never reaches this and its file is
    # unchanged, which is why the escalation costs nothing to the cases that do not need it.  A
    # claim that is simply *false* also reaches it, and pays one wasted run for the better error
    # message plain `decide` gave on the first attempt.
    admitted = any("sorryAx" in a for a in cres["axioms"].values())
    if not cres["ok"] and (not cres["axioms"] or admitted or cres["exit"] == 124):
        src, owner = gen_certificates(ext, findings, partial_src, kernel=True)
        open(cpath, "w").write(src)
        cres = leanrun.run(cpath, timeout=CERT_KERNEL_S)
        cases.log(case, "certificates_kernel_retry", certified=len(cres["axioms"]))
    open(case.path("certificates.log"), "w").write(cres["log"])

    # A theorem is certified when it is in the environment, closed, and rests on no `sorryAx`.
    failed = {re.sub(r"^theorem\s+", "", t) for t in []}
    # And when the file was killed at the wall clock, "the declaration never elaborated" is true
    # of every theorem in it and explains none of them.  That message names a claim and invites
    # the reader to go look at it; what happened is that `lean` was killed partway down the file,
    # so the theorem named first is no more at fault than the one named last, and there may be
    # nothing wrong with any of them.  A reader repairing from the list would debug a proof that
    # was never attempted.  The cause is one fact about the whole run, so it is stated as one.
    killed = cres["exit"] == 124
    certified, uncertified = {}, {}
    for thm, f in owner.items():
        ax = cres["axioms"].get(thm)
        if ax is None:
            uncertified[thm] = ("not reached: the file was killed at the wall clock"
                                if killed else
                                "no `#print axioms` line -- the declaration never elaborated")
        elif "sorryAx" in ax:
            uncertified[thm] = "admitted: the tactic errored and the claim rests on sorryAx"
        else:
            certified[thm] = ax
    del failed

    domain = next((f for f in findings if f["query"] == "domain"), {})
    out = {
        "case": case.name,
        "stage": "diagnose",
        "ok": not uncertified and cres["exit"] == 0,
        # Stated separately from the per-theorem reasons because it is not one of them.  Every
        # entry in `uncertified` then reads "not reached", which is true and says nothing about
        # what to change; this says what to change, once.
        "certificates_timed_out": killed,
        "domain": domain,
        "lean": {"diagnose": leanrun.summarize(res), "certificates": leanrun.summarize(cres)},
        "findings": findings,
        "predictions": [f for f in cres["findings"] if f.get("query") == "predict"],
        "certified": certified,
        "uncertified": uncertified,
        "counts": {
            "ambiguity": sum(1 for f in findings
                             if f["query"] == "difference" and f.get("separated")
                             and not f.get("a_dead") and not f.get("b_dead")),
            "repair_options": sum(1 for f in findings
                                  if f["query"] == "difference" and f.get("separated")
                                  and (f.get("a_dead") or f.get("b_dead"))),
            "inert_forks": sum(1 for f in findings
                               if f["query"] == "difference" and not f.get("separated")),
            "discriminating": sum(1 for f in findings
                                  if f["query"] == "difference" and f.get("discriminating")),
            "pinning": sum(1 for f in findings
                           if f["query"] == "hole" and f.get("pinning")),
            "redundancy": sum(1 for f in findings
                              if f["query"] == "equivalence" and f.get("equivalent")),
            "incompleteness": sum(1 for f in findings if f["query"] == "hole" and f.get("free")),
            "contradiction": sum(1 for f in findings if f["query"] == "deadness" and f.get("dead")),
        },
    }
    if not domain.get("cost_sorted", True):
        out["warnings"] = ["ctxUniverse is not sorted by ctxCost: the first separating context "
                           "found is not necessarily the cheapest, so 'shortest witness' is "
                           "unproven for this case"]
    json.dump(out, open(case.path("diagnosis.json"), "w"), indent=1)
    cases.log(case, "diagnose", ok=out["ok"], **out["counts"],
              certified=len(certified), uncertified=len(uncertified))
    return out
