def _caveat(decisions: list[dict], resolutions: list[dict]) -> list[str]:
    """The decisions whose answer came off an option set nobody claimed was complete.

    A pin is only as strong as the menu it was drawn from, and the summary table above counts
    every decision the same way.  This is the difference the count hides: `pinned` means the
    option set was declared to be the coordinate's whole domain, so one survivor is the value;
    `pinned_undeclared` means stage 1 recorded no domain size, so one survivor is one survivor
    *among the values offered* and the designer could be holding something that was never on
    the menu.  Step 07 admits it -- an undeclared menu makes no claim either way, and refusing it
    would be inventing a claim in the other direction -- but a report that let it pass silently
    would be presenting a measurement as a proof.

    Matched on `(round, witness)`, because both sides of the join span rounds.  A witness id is
    only unique within the round that posed it: `parallel2serial`'s `reset_data` was asked in
    round 1 off three of sixteen patterns and again in round 4 off all sixteen, and the second
    asking is exactly the one that turned an undeclared menu into a complete one.  Keyed on the
    id alone the later resolution would answer for the earlier decision, and the caveat this
    section exists to print would disappear.  The bare-id fallback is for the pre-round documents.
    """
    dated = any(r.get("round") is not None for r in resolutions)
    by_rw = {(r.get("round"), r.get("witness")): r for r in resolutions}
    by_w = {r.get("witness"): r for r in resolutions}

    def res_of(d: dict) -> dict:
        if dated and d.get("round") is not None:
            return by_rw.get((d.get("round"), d.get("witness"))) or {}
        return by_w.get(d.get("witness")) or {}

    soft = [d for d in decisions if res_of(d).get("outcome") == "pinned_undeclared"]
    if not soft:
        return []
    one = len(soft) == 1
    return [f"{len(soft)} of those decisions {'rests' if one else 'rest'} on an option set whose "
            f"completeness is undeclared: the designer left exactly one of the offered values "
            f"standing, but stage 1 recorded no size for the coordinate, so \"one survivor\" is "
            f"not the same claim as \"the only possible value\". "
            f"{'It is a decision, and it is' if one else 'They are decisions, and they are'} "
            f"marked as this kind of decision:", ""]  \
        + [f"* **`{d.get('name')}`** → `{d.get('resolved_to')}` — one of the values offered on "
           f"witness `{d.get('witness')}`; see `{d.get('name')}` in "
           f"[`QUESTIONS.md`](QUESTIONS.md) for the option list it was drawn from."
           for d in soft] + [""]


def properties_markdown(case_name: str, props: dict | None) -> str:
    """`out/PROPERTIES.md` — every stated property, and what checking it returned.

    `REPORT.md` already carries a property section, and this is not that section moved.  The
    report's job is a summary a reader gets to in one page: a table, the violations, a count of
    what was inexpressible.  This document is the record — per property, the statement as the
    prose gives it, the four verdicts, the theorem names, the axioms each theorem rests on, and
    the counterexample term where there is one.  Someone re-checking a violation by hand needs
    the Lean context term; someone reading the report needs to know a violation exists.  Trying
    to serve both from one document is how the report grew to the length nobody reads.

    Written even when nothing was checked.  A missing deliverable is indistinguishable from a
    stage that was skipped, and property checking not running is a fact about the run that the
    run should have to state.
    """
    p = props or {}
    L = [f"# Properties — `{case_name}`", "",
         "A **property** is a claim the specification makes about every legal run of the design "
         "— an invariant, a guarantee, a bound, a protocol obligation. It is not a reading to "
         "choose between. The four queries in `QUESTIONS.md` ask what the prose's *definitions* "
         "leave open; this document asks whether the prose's own *assertions* survive contact "
         "with those definitions.", ""]
    if not p:
        return "\n".join(L + [
            "## Not checked", "",
            "Property checking did not run for this case, so nothing below was established. "
            "This file exists rather than being omitted because a missing deliverable reads the "
            "same as a stage that found nothing, and the two are different facts.", ""])

    c, rows = p.get("counts", {}) or {}, p.get("properties", []) or []
    stage = p.get("stage")
    L += [f"Checked at **{stage or 'the undecided reading'}**. "
          f"**{c.get('stated', 0)}** propert{'y' if c.get('stated') == 1 else 'ies'} "
          f"extracted, **{c.get('expressible', 0)}** expressible in this projection, "
          f"**{c.get('inexpressible', 0)}** not.", ""]
    if not rows:
        L += [p.get("note", "No expressible property was extracted, so nothing was checked."),
              ""]

    for r in rows:
        # `basis` is a clause id or a list of them, and printing the list raw put a Python repr
        # -- `['C1', 'C4']` -- into a document a reader is meant to check a specification against.
        b = r.get("basis") or []
        b = [b] if isinstance(b, str) else list(b)
        L += [f"## `{r['name']}`", "",
              f"> {r.get('statement', '')}", "",
              f"*Kind*: `{r.get('kind', '?')}`."
              + (f"  *Basis*: {', '.join('`' + str(x) + '`' for x in b)}." if b else ""), ""]
        # The four questions, in the order the method asks them, each with the verdict spelled
        # as a sentence rather than as a boolean.  `entailed: false` is the one that has to read
        # unmistakably: it means this specification defines behaviour its own guarantee forbids.
        ent = r.get("entailed")
        L += ["| question | verdict |", "|---|---|",
              "| **Entailment** — does every admitted observation satisfy it? | "
              + ("**NO — the prose admits a run that breaks its own guarantee**"
                 if ent is False else "yes" if ent else "not established") + " |",
              "| **Vacuity** — is its antecedent reachable at any legal context? | "
              + ("**no — vacuously satisfied, and so constrains nothing**" if r.get("vacuous")
                 else "yes") + " |",
              "| **Inertness** — does it hold at every legal context regardless? | "
              + ("yes — it rules nothing out" if r.get("inert") else "no") + " |",
              "| **Effect on the open questions** | "
              + {"pinning": "**pins one reading** — the question retires without a query",
                 "narrowing": f"narrows to {len(r.get('survivors') or [])} of "
                              f"{r.get('n_candidates', 0)} readings",
                 "independent": "independent of every fork",
                 "vacuousP": "**no reading satisfies it** — every candidate is eliminated",
                 }.get(r.get("status"), str(r.get("status") or "—")) + " |", ""]
        if r.get("survivors"):
            L += ["Readings that survive it: "
                  + ", ".join(f"`{s}`" for s in r["survivors"]) + ".", ""]
        if ce := r.get("counterexample"):
            # `observation`, which is what `Property.lean` prints.  This read `ce["obs"]` for as
            # long as the section has existed, and no counterexample has ever carried that key --
            # so the one line that says *what the specification admits here* was silently absent
            # from every violation this pipeline has ever reported, and the paragraph ended at
            # "reached in N cycle(s)." as though the behaviour were unremarkable.
            obs = ce.get("observation")
            L += ["**Counterexample.** The property is broken at",
                  "", "```lean", str(ce.get("ctx_lean", "?")), "```", "",
                  f"reached in {ce.get('cost', '?')} cycle(s)"
                  + (f", where the specification admits `{json.dumps(obs, sort_keys=True)}`."
                     if obs else ".")
                  + "  This is a certified term, not a search result: the theorem "
                  f"below states the violation at exactly this context.", ""]
            if len(ce.get("admits") or []) > 1:
                L += [f"It is one of {len(ce['admits'])} behaviours admitted there; the property "
                      f"rejects this one. The adjudication — which of the two sentences the "
                      f"designer disowned — is in [`QUESTIONS.md`](QUESTIONS.md) under "
                      f"`{r.get('name')}`.", ""]
            else:
                L += [f"The adjudication — which of the two sentences the designer disowned — is "
                      f"in [`QUESTIONS.md`](QUESTIONS.md) under `{r.get('name')}`.", ""]
        cert = r.get("certificate") or {}
        if cert:
            L += ["**Certificates.**", ""]
            for name, ax in sorted((cert.get("axioms") or {}).items()):
                clean = "sorryAx" not in (ax or "")
                L.append(f"* `{name}` — {'kernel-checked' if clean else '**UNCERTIFIED**'}"
                         + (f" (`{ax}`)" if ax else ""))
            if not cert.get("axioms"):
                L.append(f"* the certificate did not close: {cert.get('why', 'no reason given')}")
            L.append("")
        elif r.get("name") in (p.get("uncertified") or {}):
            L += [f"**Uncertified.** {(p.get('uncertified') or {}).get(r['name'])}  The verdict "
                  f"above is what the search returned and is reported as a search result, not as "
                  f"a proved fact.", ""]

    if inx := p.get("inexpressible"):
        L += ["## Stated, and not checked", "",
              "These are claims the prose makes that could not be written over this projection. "
              "They are named rather than approximated: an approximated property that passes is "
              "worse than no property at all, because it reports a guarantee nobody established.",
              ""]
        for q in inx:
            L.append(f"* **`{q.get('name', '?')}`** — {q.get('statement', '')}  \n"
                     f"  *Why not expressible*: {q.get('why', '')}")
        L.append("")

    if p.get("pins"):
        L += ["## Questions the prose answered about itself", "",
              "Each of these forks was closed by a property the specification states, so no "
              "question was put to the designer. A pin only retires a question when its "
              "certificate closed — a search that happened to leave one survivor is not a proof "
              "that the others are impossible.", ""]
        for pin in p["pins"]:
            L.append(f"* `{pin.get('question', '?')}` → `{pin.get('reading', '?')}` "
                     f"— by `{pin.get('property', '?')}`"
                     + ("" if pin.get("certified") else "  *(uncertified: not acted on)*"))
        L.append("")
    return "\n".join(L)


def _measured_banner(oracle: dict | None) -> list[str]:
    """Guard 3 of the four in `oracle.py`: a benchmark-answered specification says so, in words.

    Not a field, not a flag, not a line in a table.  A reader who opens `REPORT.md` and skims it
    is the reader this exists for, and what they must not do is take a specification that was
    measured against an implementation for one an author decided.  Everything below this banner --
    the counts, the change log, the convergence verdict -- reads identically either way, because
    the method IS identical either way; only the authority changed, and only prose can say that.

    Two things are said and the second is the one a reader will not otherwise guess.  A reference
    implementation cannot answer "I don't care": it does one thing at each input, so a coordinate
    the design's author would have declared free comes back as whichever value the RTL happens to
    have, and the specification records a decision where the truth was a degree of freedom.  Every
    "closed" in the summary below is therefore an upper bound on what a designer would have
    closed, and the "left open, with a reason" count is a lower bound.
    """
    if not oracle or oracle.get("kind") in (None, "designer"):
        return []
    files = oracle.get("reference") or []
    named = ", ".join(f"`{f}`" for f in files) or "the design's reference implementation"
    return [
        "> **This specification was measured, not authored.**  The questions below were not put "
        "to the design's author.  They were answered by simulating " + named + ", the reference "
        "implementation that ships with this benchmark, under each question's input sequence and "
        "reading off what it did.  This is an evaluation artifact: it says what it takes to pin "
        "this document down against that implementation, and it does not say that the "
        "implementation is what anyone intended.",
        ">",
        "> One consequence is worth stating on its own, because nothing else in this file shows "
        "it.  A reference implementation cannot answer *\"either is fine\"* — it does exactly one "
        "thing at each input — so every coordinate the design's author would have declared a "
        "degree of freedom is recorded here as a decision instead. The questions counted as "
        "closed below are an upper bound on what a designer would have closed, and the ones left "
        "open are a lower bound.", ""]


def report_markdown(case_name: str, doc: dict, record: list[dict], still_open: list[dict],
                    diff: str, ver: dict,
                    resolutions: list[dict] | None = None,
                    attributed: dict | None = None,
                    properties: dict | None = None,
                    superseded: list[dict] | None = None,
                    vspace: dict | None = None,
                    oracle: dict | None = None) -> str:
    """`out/REPORT.md` — the argument that the decided specification is the right one.

    Everything in `out/` except this file is a *deliverable*: the prose a downstream reader
    would use, and the Lean a downstream tool would check.  This file is the case for them, and
    it is separate for the reason any argument is kept out of the artifact it is about -- the
    specification has to be readable without it, and it has to be possible to disagree with the
    argument without editing the specification.

    It is written by step 09 rather than step 08 because of the convergence section: whether the
    decided reading is determined everywhere is a fact about the *re-diagnosis*, and the
    re-diagnosis runs after the artifacts it is about have been written.

    There is no answer key at the end and there is no agreement sweep in the middle.  This half
    of leanSilicon has no reference implementation to sweep against and does not want one: the
    claim it makes is that every question the prose left open was found, put to the designer,
    and closed or declared open with a reason -- and each of those is checked here, against the
    record, rather than against an implementation that would have made the whole exercise a
    measurement of something else.

    `oracle` is where that paragraph stops being true, and it is why the banner it drives goes
    ABOVE the summary rather than in a footnote.  A benchmark run answers the questions from the
    design's reference implementation, which is exactly the "measurement of something else" the
    paragraph describes -- a legitimate thing to do when the thing being measured is the method,
    and a claim about the resulting specification that no reader may be left to infer from the
    absence of a designer.  Absent or naming the designer, nothing is printed: a banner on every
    ordinary run would be noise, and noise is what a reader learns to skip.
    """
    decisions = [d for d in doc.get("decisions", []) if d.get("kind") != "model"]
    model = [d for d in doc.get("decisions", []) if d.get("kind") == "model"]
    props = properties or {}

    L = [f"# {case_name} — the report", "",
         "What this specification turned out to leave open, what the designer said about "
         "it, which sentences were changed as a result, and what is still not said. The "
         "deliverables themselves carry none of this: "
         "[`spec.decided.txt`](spec.decided.txt) is the prose, "
         "[`DecidedSpec.lean`](DecidedSpec.lean) is the formal specification with its proofs, "
         "and [`QUESTIONS.md`](QUESTIONS.md) is the question list with the waveform that "
         "answered each one.", "",
         *_measured_banner(oracle),
         "## Summary", "",
         "| | |", "|---|---|",
         f"| questions the specification raised | {len(decisions) + len(still_open)} |",
         f"| put to the designer, and closed | {len(decisions)} |",
         f"| left open, with a reason | {len(still_open)} |",
         f"| sentences of the prose changed | {len(record)} |",
         f"| properties checked | {props.get('n_properties', 0)}"
         + (f", {props.get('counts', {}).get('violated', 0)} violated" if props else "") + " |",
         f"| converged | {'yes' if ver.get('converged') else 'no'}"
         + (f" (blocked by `{ver['blocked_by']}`)" if ver.get("blocked_by") else "") + " |", ""]

    if vspace:
        # How many readings of this document were still standing at each stage of the round, which
        # is the number the rest of this report's counts are counts *of*.  Two rounds that each
        # close one question read identically in the change log below and are not the same result
        # if one went 36864 -> 576 and the other went 192 -> 192.
        #
        # `|V/≈|` is the quotient by observability, and it is reported rather than used as the
        # termination rule.  It reaches 1 on a settled specification, but it also reaches 1 on one
        # blocked by `unobservable_coordinate` -- the coordinate is collapsed precisely BECAUSE
        # nothing at any legal context distinguishes its values -- and a reader shown only the
        # quotient could not tell a decided document from one with a free parameter nobody can
        # ever ask about.  `converged` above stays the verdict.
        L += ["### The space this round searched", "",
              "| | readings |", "|---|---|",
              f"| the coordinates the prose left open | {vspace['before']} |",
              f"| after formal pruning (dead, equivalent, pinned by a property) "
              f"| {vspace['after_formal']} |",
              f"| after the designer's answers | {vspace['after_feedback']} |",
              f"| up to observational equivalence, `\\|V/≈\\|` | {vspace['quotient']} |", ""]
        if vspace.get("undeclared"):
            L += [f"{len(vspace['undeclared'])} hole(s) — "
                  + ", ".join(f"`{u}`" for u in vspace["undeclared"])
                  + " — declared no menu, so they contribute an unknown factor to every count "
                    "above rather than a factor of one. The numbers are over the coordinates "
                    "whose readings this run could enumerate.", ""]

    if ver.get("blocked_by") == "violated_property":
        # The one `blocked_by` that is not a request to change what the specification means.  The
        # other three say a further round would learn nothing; this one says a further round is
        # exactly what is missing, and a reader who takes `converged: no` for a verdict on the
        # method rather than a statement about what has not been re-checked yet will draw the
        # wrong conclusion from the same word.
        vp = ver.get("violated_properties") or []
        L += [f"**Not converged, and the reason is a repair nobody has re-checked.** "
              f"This round proved that "
              f"{'a guarantee' if len(vp) == 1 else str(len(vp)) + ' guarantees'} this "
              f"specification states about itself "
              f"{'is' if len(vp) == 1 else 'are'} broken by its own definitions"
              + (f" — {', '.join('`' + p + '`' for p in vp)}" if vp else "")
              + ". The designer was shown each contradiction and said which of the two sentences "
                "was wrong, and the decisions below carry the rewrite. Whether the rewrite worked "
                "is not something this round can say: the four queries do not check properties, "
                "so a clean re-diagnosis here is clean about something else. The next round's "
                "property check, run against the repaired prose, is the check. Until it has run, "
                "`converged: no` is the honest answer.", ""]

    L += _caveat(decisions, resolutions or [])

    if (attributed or {}).get("kind") == "no_model":
        # Placed above everything else because it changes how everything else should be read.
        # The decisions below are still sound -- each was answered by the designer and each
        # is recorded with its evidence -- but the document they add up to cannot be built, so a
        # reader who takes `spec.decided.txt` away and hands it to an implementer is handing
        # over a task with no solution.  That has to be the first thing on the page, not a note
        # under a heading two screens down.
        L += ["## This specification has no implementation", "",
              "**The decided specification admits no observation at some legal context: no RTL "
              "conforms to it, and no further round of this process can change that.** The two "
              "theorems that say so are in [`DecidedSpec.lean`](DecidedSpec.lean) and both "
              "prove:", "",
              "```", *(attributed.get("pinned_theorems") or []), "```", "",
              "`decided_admits_nothing` exhibits a context at which the specification's own "
              "conditions leave nothing an implementation could output; "
              "`decided_admits_nothing_legal` proves that context is one the specification's "
              "assumptions allow, so it cannot be dismissed as out of scope.", "",
              "This is not a failure to converge for want of another round. A round closes an "
              "*open* question by asking the designer; what is wrong here is that two "
              "sentences of the prose contradict each other, the designer answered in "
              "favour of one of them, and the other is still standing. The decisions recorded "
              "below are what the designer said. The contradiction they expose is a defect "
              "in the document, and it is fixed by amending a sentence — which is a change to "
              "the author's prose, not a change this process is permitted to make on its "
              "own authority. The wording each open entry suggests is what that amendment would "
              "be.", ""]

    if model:
        L += ["Two kinds of decision are recorded, and only one of them is about what the prose "
              "*means*. A *projection* decision revises how the question is put rather than what "
              "the answer says — the interface the queries are driven through was wrong, and "
              "either the formalization or the specification is the one that had it wrong. It "
              "settles no reading, so it patches no sentence; where the specification is the "
              "side at fault, the repair is stated here and in the note beside each question "
              "that the mismatch cost:", ""]
        for d in model:
            L.append(f"* **`{d.get('name')}`** → `{d.get('resolved_to')}` — {d.get('why', '')}")
        L.append("")

    L += ["## What changed, and on whose authority", ""]
    if not record:
        L += ["Nothing. Every question this specification raised was answered without requiring "
              "the prose to change, which is itself a result.", ""]
    for h in record:
        # Matched on the round as well as the name.  With a multi-round case the decision record
        # is the whole run's, and a hunk carries the round it was authored in; name alone would be
        # right today, because a question closed in round 1 cannot be re-asked in round 2, but it
        # would be right by accident rather than by construction.
        d = next((x for x in doc.get("decisions", [])
                  if x.get("name") == h.get("decision")
                  and (h.get("round") is None or x.get("round") == h.get("round"))),
                 next((x for x in doc.get("decisions", [])
                       if x.get("name") == h.get("decision")), {}))
        rnd = d.get("round", h.get("round"))
        L += [f"### `{h['decision']}` → `{d.get('resolved_to', '?')}`", "",
              f"Clause {h['clause']}, bytes {h['original_span'][0]}–{h['original_span'][1]}. "
              + (f"Decided in round {rnd} on witness " if rnd is not None
                 else "Resolved on witness ")
              + f"`{d.get('witness', '?')}`; the question, the readings and "
              f"the waveform that separated them are under `{d.get('name')}` in "
              f"[`QUESTIONS.md`](QUESTIONS.md).", "",
              "before:", "", "```", h["original"], "```", "",
              "after:", "", "```", h["new"], "```", ""]
        if d.get("evidence"):
            L += [f"**Why.** {d['evidence']}", ""]
        if d.get("consequence"):
            L += [f"**What this settles.** {d['consequence']}", ""]

    # A decision that changed no prose is invisible in the section above, and the summary counts
    # it.  That gap is small in a one-round case and not small across four: a hole whose value was
    # pinned and written into `Cfg` alone leaves the sentence that failed to state it exactly as
    # it was, so "sentences changed" and "closed by a decision" come apart, and a reader is owed
    # the reason rather than the subtraction.
    #
    # Two ways to change no prose, and they are opposites.  One decision never wrote a hunk.  The
    # other wrote one and a later round wrote over it -- `patch.supersede` drops the earlier hunk,
    # so it is absent from `record` here and reads, without this split, exactly like the first.
    # It is not the first, and the difference is the whole point: on `accu`, round 1 fixed
    # `grouping` to a sliding window and round 2's property check proved that reading breaks
    # `valid_out_single_cycle` and rewrote the same sentence the other way.  Reported as "closed
    # without the prose changing", that decision appears in this file carrying the consequence
    # "an implementer must not clear the word counter to zero on a pulse" -- the opposite of what
    # `spec.decided.txt` next to it now requires.  A reader following the report would build the
    # circuit this run exists to have ruled out.
    # Keyed by name AND round, both here and against `record`.  A name is not unique across a
    # run: a violated property that survives its own repair is adjudicated again under the same
    # name in the round after, which is precisely the case that produces a supersession.  Keyed by
    # name alone, round 2's `pulse_count_bounded` reports itself as having overturned itself, and
    # round 1's disappears from both lists -- excluded from the silent one by round 2's hunk and
    # from this one by round 2's decision.
    over = {(s.get("decision"), s.get("round")): s for s in (superseded or [])}
    wrote = {(h.get("decision"), h.get("round")) for h in record}
    silent = [d for d in decisions
              if (d.get("name"), d.get("round")) not in wrote
              and (d.get("name"), d.get("round")) not in over]
    overturned = [d for d in decisions if (d.get("name"), d.get("round")) in over
                  and (d.get("name"), d.get("round")) not in wrote]
    if silent:
        L += ["Some questions were closed without the prose changing — the answer is recorded in "
              "the formal specification, and the sentence that left it open was not itself "
              "wrong, only silent:", ""]
        for d in silent:
            r = f" *(round {d['round']})*" if d.get("round") is not None else ""
            L.append(f"* **`{d.get('name')}`** → `{d.get('resolved_to')}`{r} — "
                     + (d.get("consequence") or d.get("evidence") or ""))
        L.append("")

    if overturned:
        L += ["Some questions were answered twice, and the later answer is the one in force. A "
              "round exists to ask what the one before it could not, and part of what it can "
              "find out is that an earlier repair was wrong — the property check runs against "
              "the prose that repair produced, so the evidence that overturns it does not exist "
              "until the round after. The sentence carries the later rewrite and the earlier one "
              "is not in the specification at all. What each of these says below is what it said "
              "at the time, and is superseded:", ""]
        for d in overturned:
            s = over[(d["name"], d.get("round"))]
            L.append(f"* **`{d.get('name')}`** → `{d.get('resolved_to')}` *(round "
                     f"{d.get('round')}, overturned in round {s.get('by_round')} by "
                     f"`{s.get('by_decision')}`)* — "
                     + (d.get("consequence") or d.get("evidence") or ""))
        L.append("")

    L += ["## Unspecified, and left that way", ""]
    if not still_open:
        L += ["Nothing: every coordinate of the formal specification is fixed by a decision.", ""]
    else:
        # The paragraph this replaced said the projection proves no legal context exposes the
        # difference.  That is one of the two ways a coordinate stays open and it was being
        # printed for both.  The other is a coordinate the projection DOES expose and the
        # designer declined to settle -- an author who genuinely does not mind, say -- and for
        # that one the sentence was simply false.  Which of the two applies is in each entry's
        # own `why`, where the record is required to say it; what the section asserts on its own
        # is only what is common to both.
        L += ["These are places the prose says nothing and the designer could not be made to "
              "say anything either. They are listed rather than filled: a value chosen to make "
              "the specification look complete would be an invention, and the specification "
              "would then be wrong in a way nothing could detect. Each entry says which it is — "
              "a difference no legal context exposes, or one the designer declined to settle.",
              ""]
        for o in still_open:
            L.append(f"* **`{o.get('name', o['field'])}`** (`{o['field']}`) — {o.get('why', '')}")
            if o.get("note_for_spec"):
                L.append(f"  Suggested wording: *{o['note_for_spec']}*")
        L.append("")
        if (attributed or {}).get("kind") == "undetermined_by_open_coordinate":
            # Without this the section is a list of admissions and the reader has to take on
            # trust that the rest of the specification is sound.  The theorems say it is: they
            # are the difference between "something here is undetermined" and "exactly these
            # coordinates are undetermined, and pinning them determines everything else".
            names = attributed.get("pinned_theorems") or []
            dead = attributed.get("dead_pinnings") or []
            live = [n for n in names if n.startswith("determined_given_")]
            total = len(live) + len(dead)
            L += ["That these are the *only* undetermined coordinates is checked rather than "
                  "asserted. `decided_determined` — one admitted observation per legal context — "
                  "does not hold, and cannot, while a coordinate above is free. What does hold, "
                  "over the same domain, is the same statement with the open coordinates "
                  "pinned: [`DecidedSpec.lean`](DecidedSpec.lean) carries one theorem per "
                  f"combination of values they can take, {total} in all, and every one of them "
                  "proves. So the indeterminacy is located at the coordinates named above and "
                  "nowhere else in the specification.", ""]
            if dead:
                # Not every pinning can be asked the same question, and printing them as if it
                # could would overstate the result by claiming determinacy where what was proved
                # is the opposite failure.
                L += [f"{len(live)} of those combinations are determined outright "
                      f"(`determined_given_`). The other {len(dead)} are not, and for the "
                      "opposite reason to ambiguity: pinning to those values leaves the "
                      "specification with no model at all — at some legal context it admits "
                      "nothing — so `determinedEverywhere`, which asks for *exactly one*, is the "
                      "wrong question there. Each of them carries instead the pair of claims that "
                      "is right for it: `never_ambiguous_given_`, that two readings are never "
                      "admitted at once, and `dead_somewhere_given_`, that at some legal context "
                      "none is. The value being pinned is one the rest of the prose contradicts; "
                      "which sentence does the contradicting is under that question above.", ""]
            L += ["```", *names, "```", ""]
        elif (attributed or {}).get("kind") == "undetermined_open_unattributed":
            # The attributed case above earns a paragraph saying the list is complete.  This one
            # must not simply omit that paragraph: a reader who has seen the other report reads
            # its absence as an oversight, and a reader who has not reads the list of open
            # coordinates as though it had been checked.  Neither is what happened, so the
            # weaker claim is stated in the same place, at the same length, as the stronger one.
            n, lim = attributed.get("pinnings_declined"), attributed.get("pinnings_limit")
            L += ["That these are the *only* undetermined coordinates is **not** checked here, "
                  "and the difference from a run that does check it matters. The check is one "
                  "theorem per combination of values the open coordinates can take, proving that "
                  "pinning them determines everything else; with "
                  f"{len(still_open)} of them open there are {n} such combinations, past the "
                  f"{lim} [`DecidedSpec.lean`](DecidedSpec.lean) will write. So what holds is "
                  "the weaker pair: the specification is undetermined somewhere — "
                  "`decided_determined` does not prove, and that failure is the only one in the "
                  "file — and the coordinates above are the ones this run knows it left open. "
                  "Whether something else is undetermined too is not ruled out by anything here. "
                  "A round that closes some of these brings the product back under the limit, "
                  "and the claim back within reach.", ""]

    if diff.strip():
        L += ["## The diff", "", "```diff", diff.rstrip(), "```", ""]

    L += ["## What the prose claims about itself", ""]
    if not props:
        L += ["Not checked. Property checking is an independent stage and its absence is "
              "reported as an absence, not as a pass.", ""]
    elif not props.get("n_properties"):
        L += [props.get("note", "No expressible property was extracted, so nothing was "
                                "checked."), ""]
    else:
        c = props.get("counts", {})
        L += [f"A property is a claim the specification makes about every legal run of the "
              f"design — an invariant, a guarantee, a bound. They are not readings to choose "
              f"between: they are checked against the readings. "
              f"**{c.get('expressible', 0)} of {c.get('stated', 0)}** stated properties were "
              f"expressible in this projection and each was put four questions — is it entailed, "
              f"is it vacuous, does it pin an open fork, is it independent of every fork.", "",
              "| property | kind | entailed | vacuity | effect on the open questions |",
              "|---|---|---|---|---|"]
        for r in props.get("properties", []):
            ent = ("**violated**" if r.get("entailed") is False else
                   "yes" if r.get("entailed") else "—")
            vac = ("**vacuous**" if r.get("vacuous") else
                   "inert" if r.get("inert") else "live")
            st = r.get("status")
            eff = ("pins `" + (r.get("survivors") or ["?"])[0] + "`" if st == "pinning" else
                   f"narrows to {len(r.get('survivors') or [])} of "
                   f"{r.get('n_candidates', 0)}" if st == "narrowing" else
                   "independent" if st == "independent" else
                   "no reading satisfies it" if st == "vacuousP" else str(st or "—"))
            L.append(f"| `{r['name']}` | {r.get('kind', '')} | {ent} | {vac} | {eff} |")
        L.append("")
        if c.get("violated"):
            L += ["A **violated** property is the sharpest finding this stage produces: the "
                  "prose states a guarantee and the same prose, read as a relation, admits a run "
                  "that breaks it. The context and the offending observation are certified in "
                  "`prop_violated_*` and `prop_witness_*`, so this is not a search result. It is "
                  "reported and not repaired — which sentence gives way is the author's call.",
                  ""]
            for r in props.get("properties", []):
                if r.get("entailed") is False:
                    ce = r.get("counterexample") or {}
                    L += [f"* **`{r['name']}`** — *{r.get('statement', '')}* — broken at "
                          f"`{ce.get('ctx_lean', '?')}` ({ce.get('cost', '?')} cycle(s))."]
            L.append("")
        if c.get("vacuous"):
            L += ["A **vacuous** property is satisfied because its antecedent never holds "
                  "anywhere in the domain. That is not a property the specification enforces; it "
                  "is a sentence that reads like one, and the distinction matters to whoever "
                  "implements against it.", ""]
        if props.get("inexpressible"):
            # Printed rather than dropped: a property outside the projection is a claim the
            # prose makes that nothing here checked, and silence about it would read as a pass.
            L += [f"{len(props['inexpressible'])} stated propert"
                  f"{'y was' if len(props['inexpressible']) == 1 else 'ies were'} not "
                  f"expressible in this projection and "
                  f"{'was' if len(props['inexpressible']) == 1 else 'were'} not checked:", ""]
            for q in props["inexpressible"]:
                L.append(f"* **`{q.get('name', '?')}`** — {q.get('why', '')}")
            L.append("")

    ind = ver.get("designer_indifferent") or []
    L += ["## What the designer would not settle", ""]
    if not ind:
        L += ["Nothing: every question the projection proved observable, the designer "
              "answered.", ""]
    else:
        L += ["Questions where the designer accepted **every** reading — either by picking a "
              "waveform all of them admit, or by saying outright that the choice is free. Two "
              "things can cause the first, and they are not the same result, so the certificate "
              "is printed with each one. With `separation certified: yes`, the projection "
              "*proved* the readings differ at a legal context and the answer still did not tell "
              "them apart, which makes the freedom real. With `no`, the separation was found by "
              "search and never certified, so the silence may be the projection's own. Either "
              "way the question is reported rather than closed by a guess: a coordinate the "
              "author does not care about should be *stated* to be free, not filled in by us.",
              ""]
        for i in ind:
            L.append(f"* **{i.get('question')}** — {i.get('why')} "
                     f"(separation certified: "
                     f"{'yes' if i.get('separation_certified') else 'no'})")
        L.append("")

    L += ["## What this report does not claim", "",
          "That the decided specification says what the designer *meant*, in general. What is "
          "checked is narrower and is checked mechanically: every place the prose admitted more "
          "than one behaviour was found by evaluating the semantics over the whole context "
          "domain; each was put to the designer as a waveform choice at a context where the "
          "readings provably differ; and every coordinate of the formal specification is either "
          "named by one of those answers or listed above as open. Nothing was defaulted. What "
          "the designer was never asked — because no legal context separates it, or because the "
          "extraction never modelled it — is named in "
          "[`QUESTIONS.md`](QUESTIONS.md) rather than left to be inferred from silence.", ""]
    return "\n".join(L) + "\n"
