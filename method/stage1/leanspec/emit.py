# ------------------------------------------------------------------------ `probe.json`

#: Port names that mean "this is the clock".  Whole names, matched case-insensitively, and
#: deliberately a closed list rather than a substring rule: `clk_div` and `clk_en` are ordinary
#: driven inputs on a design that divides or gates its clock, and a rule that swallowed them would
#: take a signal the specification constrains out of the stimulus entirely.  A name outside this
#: list yields `clock: null` and stays in `inputs`, which is the conservative direction — the
#: signal is still driven, and the timing note is the thing that goes missing.
_CLOCK_NAMES = frozenset(
    ("clk", "clock", "clk_i", "i_clk", "clk_in", "clkin", "sys_clk", "sysclk", "clka"))


def probe_document(extraction: dict) -> dict:
    """`probe.json`, derived from the extraction's port list.

    This used to be a pass of its own — a whole `claude -p` session, the ninth, whose entire job
    was to copy the port list into a second shape.  It is not a judgement.  Every `probe.json`
    this method has produced (21 files, two designs, every round and every sweep) is exactly what
    this function returns, and the three fields that could in principle have varied did not:

      * `sample` was `after_edge` in all of them.  It is not a free choice — `Ctx` is a trace of
        driven steps and `Obs` is what is read out of them, and reading before the edge would make
        step *n*'s observation a function of step *n-1*'s input, which is not the shape any
        `admits` in this corpus is written in.  A specification that wants the other convention
        can still have it; it is now a hand edit to a generated file rather than the default
        answer of a session that had no reason to prefer either.

      * `reset` was `null` in all of them, including `Prob067_countslow`, which has a port
        literally named `reset`.  That is the rule, not an oversight: a reset port is DRIVEN, it
        appears in `Ctx` like every other input, and lifting it into a harness preamble would
        drive it twice — once by the preamble and once by the trace — and hide the reset protocol
        from exactly the queries that exist to ask about it.  `reset` is for a reset the trace
        does *not* contain.

      * `clock` was the design's clock port and `inputs`/`outputs` were the remaining ports in
        extraction order.

    Deriving it also closes a defect surface that no check covered.  `ctxJson` names ports in
    pass 5 and this document named them in pass 9, four sessions apart, with nothing between them
    requiring the two to agree; and `author.in_passes` had to carry a paragraph about discarding a
    stale probe left behind by an abandoned attempt, because the gate for a document that already
    exists cannot tell "written now" from "written last time".  A document computed from the
    extraction on every entry has neither problem.
    """
    ports = extraction.get("ports") or []
    clock = next((p["name"] for p in ports
                  if p.get("dir") == "in" and p.get("name", "").lower() in _CLOCK_NAMES), None)
    return {"clock": clock,
            "reset": None,
            "inputs": [p["name"] for p in ports if p.get("dir") == "in" and p["name"] != clock],
            "outputs": [p["name"] for p in ports if p.get("dir") == "out"],
            "sample": "after_edge"}


#: The `Case` record, which is wiring and nothing else.  See `case_stanza`.
_CASE = """\
/-- The `Case` record the queries are run through.  Seven bindings, each naming the declaration
    above that it is the field for; written by the driver (`emit.case_stanza`) rather than by a
    session, because there is no other value it could take.  `Case` is what `LeanSpec.Core`'s
    queries range over, and its fields are `REQUIRED_DEFS` minus the ones that are not part of the
    frame — so a `case` that named anything else would be naming a declaration the checker does
    not require and the queries cannot use. -/
def case : LeanSpec.Case Ctx Obs :=
  { ctxs    := ctxUniverse
    obs     := obsUniverse
    legal   := legal
    cost    := ctxCost
    ctxJson := ctxJson
    ctxLean := ctxLean
    obsJson := obsJson }
"""

_CASE_DECL = re.compile(r"(?m)^\s*def\s+case\s*:")


def case_stanza(src: str) -> str | None:
    """The `case` wiring, or `None` if the file already declares it.

    The second thing taken off the agent after `probe.json`, and for the same reason: it is not a
    judgement.  Across the 24 `Partial.lean` files this method has produced, 23 declare `case` and
    all 23 declare the *same* one — 21 in Lean's newline-separated record syntax and 2 in the
    comma-leading one, which is a difference of punctuation and not of content.  Seven fields,
    seven declarations to bind them to, and every one of those names is in `schema.REQUIRED_DEFS`
    already: there is no second way to write it that would elaborate.

    Removing it from the `render` pass is worth more than the lines it saves, and the reason is
    ordering rather than typing.  `case` is the only thing in that pass that reads a declaration
    another pass wrote — `obsUniverse`, from `obs` — so as long as a session writes it, `render`
    cannot be authored until `obs` has finished, and the two passes are serial for the sake of
    eight lines of boilerplate.  With the wiring generated, `obs`, `render` and `properties` read
    nothing of each other's.

    It goes at the END of the file rather than where a session used to put it, because the driver
    appends it once the passes are done and appending is the only edit that cannot disturb what
    they wrote.  Nothing inside `Partial.lean` refers to `case`; the queries that do are in the
    files `diagnose.py` emits, which import this one.

    A file that already declares `case` is left alone and `None` is returned. That is what makes
    this safe on the artifacts already on disk: a carried round's `Partial.lean` is round one's,
    an earlier run's was written by a session, and re-appending would put two `case`s in a file
    that Lean would then reject for the driver's reason rather than the author's.
    """
    return None if _CASE_DECL.search(src) else _CASE


# --------------------------------------------------------------------- reading `Cfg`

_CFG_BLOCK = re.compile(r"(?ms)^structure\s+Cfg\s+where\s*\n(.*?)^\s*deriving\b")
_FIELD = re.compile(r"(?m)^\s+([A-Za-z_][A-Za-z_0-9]*)\s*:\s*([^:=\n]+?)\s*(?::=\s*(.+?))?\s*$")


def cfg_fields(partial_src: str, names: list[str] | None = None) -> list[dict]:
    """The `Cfg` fields, in declaration order, with type and Lean-level default.

    Parsed from `Partial.lean` rather than from `extraction.json` because `Cfg` is the thing
    `decidedCfg` has to be total over: a field the agent added without a matching entry in
    stage 1 is precisely the kind of undeclared coordinate this module exists to refuse.

    Line comments were skipped from the start; block comments were not, and a field is a name, a
    colon and some text, which is also what the second line of

        /-- H3 -- how many values are already counted at release.  Closed
        domain: the count within a group is strictly between 0 and 4. -/

    looks like.  That parsed as a coordinate called `domain`, and a phantom coordinate is worse
    than a missed one: `derive` is total over this list, so it would refuse the whole decided
    spec for a field no decision can ever name, and the error would point at the decisions.

    Handling the comment shape stopped that instance; `names` stops the class.  Pass
    `schema.cfg_field_names(src, ext)` — the field list as the *elaborated environment* has it —
    and anything this parser reads that Lean does not know about is dropped rather than carried
    into `derive`.  The reverse gap, a field Lean has and this parser could not read, is not
    silently filled here: `schema.check_partial` reports it, because a coordinate with no type
    and no default is not something a decided specification can be written from.
    """
    m = _CFG_BLOCK.search(partial_src)
    if not m:
        return []
    out, in_doc = [], False
    for line in m.group(1).splitlines():
        opens, closes = ("/-" in line), ("-/" in line)
        if in_doc:
            in_doc = not closes
            continue
        if opens:
            # A one-line `/-- ... -/` is already inert here (it does not match `_FIELD`), but
            # skipping it costs nothing and says why the next lines are being skipped.
            in_doc = not closes
            continue
        if not line.strip() or line.strip().startswith("--"):
            continue
        line = re.sub(r"\s+--.*$", "", line)
        f = _FIELD.match(line)
        if f and (names is None or f.group(1) in names):
            out.append({"field": f.group(1), "type": f.group(2).strip(),
                        "default": (f.group(3) or "").strip(),
                        "kind": ("choice" if f.group(1).startswith("c_") else
                                 "hole" if f.group(1).startswith("h_") else "other")})
    return out


# ------------------------------------------------------------------ the derivation

def derive(fields: list[dict], doc: dict) -> tuple[dict, list[dict], list[str]]:
    """`decidedCfg`'s assignments, the fields left open, and every reason to refuse.

    Returns `(assignments, still_open, errors)`.  `errors` non-empty means no specification is
    emitted at all: a partially-derived decided spec is a spec with an invented coordinate in
    it, and that is the failure mode the whole pipeline is arranged around.
    """
    errs: list[str] = []
    by_field: dict[str, dict] = {}
    for i, d in enumerate(doc.get("decisions", [])):
        if d.get("kind") in ("model", "violation"):
            # A `model` decision widened the projection; it fixes no coordinate of `Cfg` and is
            # carried into the output as history, not as an assignment.  A `violation` decision
            # fixes no coordinate either, for a different reason: it says which of two contradic-
            # tory sentences the author disowned, and that repair lands in the prose and in the
            # next round's formalization.  Requiring a `cfg_field` of it would force the author to
            # name a coordinate the adjudication did not settle, which is exactly the invented
            # assignment the rest of this function exists to refuse.
            continue
        f = d.get("cfg_field")
        if not f:
            errs.append(f"decision[{i}] ({d.get('name')!r}): no `cfg_field` -- a decision that "
                        f"names no coordinate of `Cfg` cannot be part of a decided spec")
            continue
        if not d.get("cfg_value"):
            errs.append(f"decision[{i}] ({d.get('name')!r}): no `cfg_value`")
        if f in by_field:
            errs.append(f"decision[{i}] ({d.get('name')!r}): `{f}` is decided twice, by "
                        f"{by_field[f].get('name')!r} and by {d.get('name')!r}")
        by_field[f] = d

    open_by_field = {o.get("cfg_field"): o for o in doc.get("remaining_open", [])}
    for f, o in open_by_field.items():
        if not o.get("why"):
            errs.append(f"remaining_open[{f!r}]: no `why` -- a coordinate left open has to say "
                        f"what the prose failed to state, or it is indistinguishable from one "
                        f"that was forgotten")

    known = {f["field"] for f in fields}
    for f in sorted(set(by_field) | set(open_by_field)):
        if f not in known:
            errs.append(f"`{f}` is not a field of `Cfg` in Partial.lean (fields: "
                        f"{sorted(known)})")

    assignments, still_open = {}, []
    for fl in fields:
        f = fl["field"]
        if f in by_field and f in open_by_field:
            errs.append(f"`{f}` is both decided and listed as remaining open")
        elif f in by_field:
            assignments[f] = by_field[f]["cfg_value"]
        elif f in open_by_field:
            still_open.append(dict(fl, **open_by_field[f]))
        else:
            errs.append(
                f"`{f}` is neither decided nor declared open.  Every coordinate of `Cfg` has to "
                f"be accounted for: emitting a decided spec that leaves this one at its Lean "
                f"default would put a value in the specification that no answer from the "
                f"designer ever justified, which is the one thing this framework must not do.")
    return assignments, still_open, errs


# ------------------------------------------------------------------- the Lean output

def _one_line_record(base: str, assignments: dict) -> str:
    """`{ base with f := v, ... }`, on a single line.

    Deliberately not wrapped.  A structure update split across lines is a parse error under
    some indentations, and a parse error here does not fail loudly -- Lean recovers, the `def`
    keeps a `sorryAx` body, and every certificate downstream then reports `sorryAx` in its
    axioms while the source contains no `sorry` at all.  That is an expensive half hour, and
    the whole cost of avoiding it is a long line.
    """
    if not assignments:
        return base
    inner = ", ".join(f"{f} := {v}" for f, v in assignments.items())
    return "{ " + base + " with " + inner + " }"


def decide_partial(src: str, assignments: dict) -> tuple[str, list[str]]:
    """`Partial.lean` with `Cfg`'s field defaults set to the decided values.

    This is the edit the agent used to make by hand between rounds, and it has to happen
    somewhere: the diagnosis queries are asked about `defaultCfg`, so re-diagnosing a decided
    specification against a `Cfg` whose defaults are still the *undecided* ones reports the
    same freedom the designer just closed, and the case never converges no matter how many
    questions were answered.  Deriving it from the decision record instead of writing it by
    hand is the whole point: a hand edit here can fill a coordinate no query settled, and it
    would look exactly like this one.

    Only the `structure Cfg` block is touched.  The field names occur again in `cfgPin_*` and
    `cfgPins_*`, and those must not move: a pin is the coordinate's *option*, not its value, and
    the menus are where step 05 gets the alternatives a question is built from.  Rewriting a pin to
    the decided value would delete the record of what else was on offer, so a later round could not
    show that the coordinate had ever been open.

    (This paragraph used to name a `cfgEnum` declaration as the thing that must not move.  No
    recorded `Partial.lean` has ever declared one -- 0 of 24 -- so the name was wrong even though
    the rule is right.)
    """
    m = _CFG_BLOCK.search(src)
    if not m:
        return src, []
    done: list[str] = []

    def fix(line: str) -> str:
        f = _FIELD.match(re.sub(r"\s+--.*$", "", line))
        if not f or f.group(1) not in assignments:
            return line
        name = f.group(1)
        done.append(name)
        indent = line[:len(line) - len(line.lstrip())]
        return (f"{indent}{name} : {f.group(2).strip()} := {assignments[name]}"
                f"    -- decided (steps/06_decision.json)")

    body = "\n".join(fix(l) for l in m.group(1).splitlines()) + "\n"
    return src[:m.start(1)] + body + src[m.end(1):], done


def gen_lean(case_name: str, fields: list[dict], assignments: dict, still_open: list[dict],
             doc: dict, findings: list[dict], partial_src: str = "",
             unsat_ctx: str | None = None,
             dead_pins: set[str] | None = None) -> tuple[str, list[str]]:
    """The decided specification, as Lean, with one theorem per claim it makes.

    Returns `(source, errors)`.  A non-empty `errors` means a refutation could not be written
    as a Lean term at all; the source is still returned so the failure can be read, but the
    step that called this must not report the specification as delivered.

    No evidence, and no narration.  This file used to open with a paragraph per decision --
    which question it answered, what the reference showed, why that settles it -- and it was
    the wrong place for all of it.  A comment is not checked by anything, it drifts from the
    record it paraphrases, and it sits between the reader and the thing they came for.  The
    argument now lives in `out/REPORT.md`, which is generated from the same record; what stays
    here is the specification, the theorems, and a one-line label per theorem saying what it
    claims.
    """
    L = [HEADER.format(case=case_name), IMPORTS, ""]

    L.append("/-- The decided configuration, derived from the decision record rather than "
             "hand-written. -/")
    L.append(f"def decidedSpec : Cfg := {_one_line_record('defaultCfg', assignments)}")
    L.append("")
    if still_open:
        L.append("-- Left open, with a reason recorded in `out/REPORT.md` -- not defaulted:")
        for o in still_open:
            L.append(f"--   {o['field']}")
        L.append("")

    # ---- the property that makes it a *decided* spec
    L.append("/-- Exactly one observation is admitted at every legal context in the domain: the")
    L.append("stopping condition of `goal.md`'s refinement loop, over the same universe every")
    L.append("diagnosis was searched over.  With a field still open this is the STRONGER claim --")
    L.append("that the open coordinate changes nothing observable here -- and it fails whenever")
    L.append("the coordinate is free.  See the per-pinning theorems below for the weaker one. -/")
    L.append("theorem decided_determined :")
    L.append("    determinedEverywhere (admits decidedSpec) obsUniverse ctxUniverse legal "
             "= true := by")
    L.append("  decide +kernel")
    L.append("#print axioms decided_determined")
    L.append("")

    # ---- and, when something is open, the claim that survives its being open
    #
    # `decided_determined` asks the specification to pick one observation per context.  A case
    # with a free open coordinate cannot do that and should not pretend to: the whole content of
    # "left open" is that two behaviours are still admitted.  Failing the step there would be
    # reporting a finding about the SPECIFICATION as a fault in the emission.
    #
    # What is true, and provable, is the same statement with the open coordinates universally
    # pinned: for every value each of them can hold, the rest of the specification is determined.
    # That is what attributes the indeterminacy -- it locates it AT the declared-open coordinate
    # instead of leaving it as an unexplained hole somewhere in the document.  A case whose
    # `decided_determined` fails and whose pinned theorems also fail has a second problem, and
    # the two are worth telling apart, so both are emitted and step 07 reads both.
    #
    # A pinning can fail for the same two opposite reasons the unpinned claim can, and one of
    # them is not a problem: pinning an open coordinate to a value the rest of the prose
    # contradicts leaves that pin admitting nothing, which fails a test for *exactly one*.
    # `cvdp/digital_dice_roller` round 1 is the case -- `c_range_scope` is still open there, and
    # four of its twelve pinnings set it to `all_time`, the reading C4 makes unsatisfiable.  For
    # those, `determinedEverywhere` is the wrong question, so a pin named in `dead_pins` (which
    # step 07 fills from a first pass) gets the two claims that are right for it instead: it is
    # never ambiguous, and it is dead somewhere.  Together those say which way it failed, and the
    # first still fails -- correctly -- if the pin is genuinely ambiguous.
    pins, why_not, sampled, product = (_pinnings(partial_src, still_open) if not unsat_ctx
                                       else ([], None, [], 0))
    dead = set(dead_pins or ())
    if still_open and not pins and not unsat_ctx:
        L.append(f"-- No per-pinning determinacy theorem: {why_not}.")
        # Machine-readable, for the same reason `SAMPLED-PINNING` below is: `pipeline` has to
        # know WHY there are none, and the two reasons are different findings.  Too many to write
        # still says where the indeterminacy is -- at the coordinates named above, and there are
        # simply a lot of them -- and the round can go on.  A coordinate with no enumerable axis
        # says nothing was quantifiable at all, and that is not something to wave through.  The
        # count is written rather than the sentence re-parsed: the sentence is for a reader.
        if product:
            L.append(f"-- PINNINGS-DECLINED: {product} > MAX_PINNINGS={MAX_PINNINGS}")
        L.append("")
    if pins and sampled:
        # Machine-readable, because `pipeline._attribute_indeterminacy` has to say the same
        # thing in the finding and must not restate it from its own reading of the types.
        for f in sampled:
            L.append(f"-- SAMPLED-PINNING: {f}")
        L.append("--")
        L.append("-- Read what the theorems below quantify over.  " + ", ".join(
            f"`{f}`" for f in sampled) + (" has" if len(sampled) == 1 else " have")
            + " a type with no finite")
        L.append("-- enumeration, so the pinnings are taken from the menu `cfgPins_` offered the")
        L.append("-- oracle rather than from the coordinate's domain.  Each theorem is exactly")
        L.append("-- true -- it names values and proves determinacy at them -- but together they")
        L.append("-- cover the menu and not the domain, so they locate the indeterminacy at this")
        L.append("-- coordinate only as far as the menu reaches.  A value never offered is a")
        L.append("-- value nothing here rules on.")
        L.append("")
        # The tags above were read out of `Partial.lean` with a regex, and each pinning below
        # looks its tag up again at elaboration time.  This is those two readings agreeing.
        # Without it a tag the regex mis-read -- or a menu edited between the two -- would take
        # `_menu_term`'s `getD` branch, and the pinning would be a theorem about the DEFAULT
        # configuration wearing the name of a menu entry: elaborated, proved, and about the wrong
        # specification.  That is the silent wrong answer `_lean_reading` refuses one tag at a
        # time, and it has to be refused here too now that this path no longer goes through it.
        #
        # The list is built from `pins` rather than by re-reading the menu, so what the theorem
        # checks is the axis actually consumed and not a second parse that could differ from it.
        nm_of = {o["field"]: (o.get("name") or re.sub(r"^[hc]_", "", o.get("field", "")))
                 for o in still_open}
        for f in sampled:
            tags, seen = [], set()
            for pin in pins:
                for g, t, _ in pin:
                    if g == f and t not in seen:
                        seen.add(t)
                        tags.append(t)
            L.append(f"/-- `{f}`'s menu, as this file read it when it wrote the pinnings below.")
            L.append("The theorems below take their values from this menu by looking each tag up,")
            L.append("so a tag that is not on it would silently pin the default instead. -/")
            L.append(f"theorem menu_{f} :")
            L.append(f"    cfgPins_{nm_of[f]}.map (·.1) = ["
                     + ", ".join(f'"{t}"' for t in tags) + "] := by")
            L.append("  decide +kernel")
            L.append(f"#print axioms menu_{f}")
            L.append("")
    for pin in pins:
        name = "determined_given_" + "__".join(f"{f}_{t}" for f, t, _ in pin)
        shown = ", ".join(f"`{f} := {t}`" for f, t, _ in pin)
        stem = name[len("determined_given_"):]
        is_sampled = any(f in sampled for f, _, _ in pin)
        if name in dead:
            L.append(f"/-- Pinning the open coordinate(s) to {shown} leaves the specification")
            L.append("with NO model: at some legal context nothing at all is admitted.  So this")
            L.append("pinning is not determined, and the reason is the opposite of ambiguity --")
            L.append("`never_ambiguous_given_` says the specification never admits two readings")
            L.append("here, and `dead_somewhere_given_` says it sometimes admits none.  The value")
            L.append("pinned is one the rest of the prose contradicts; which sentence does the")
            L.append("contradicting is in `out/REPORT.md`. -/")
            # `pinned_given_`, not `pinned_determined_given_`: the configuration this names is one
            # the theorems below prove is NOT determined, and an identifier should not say the
            # opposite of what the block it heads proves.
            L.append(f"def pinned_given_{stem} : Cfg := "
                     + _one_line_record("decidedSpec", {f: term for f, _, term in pin}))
            L.append(f"theorem never_ambiguous_given_{stem} :")
            L.append("    ctxUniverse.all (fun c => !legal c || "
                     f"(admitSet (admits pinned_given_{stem}) obsUniverse c).length ≤ 1) "
                     "= true := by")
            L.append("  decide +kernel")
            L.append(f"#print axioms never_ambiguous_given_{stem}")
            L.append(f"theorem dead_somewhere_given_{stem} :")
            L.append("    ctxUniverse.any (fun c => legal c && "
                     f"(admitSet (admits pinned_given_{stem}) obsUniverse c).isEmpty) = true := by")
            L.append("  decide +kernel")
            L.append(f"#print axioms dead_somewhere_given_{stem}")
            L.append("")
            continue
        L.append(f"/-- Pinning the open coordinate(s) to {shown} leaves the specification")
        if is_sampled:
            L.append("determined at every legal context.  The pinning is not a decision and this")
            L.append("is not evidence for one, and the value pinned came off an offered menu")
            L.append("rather than off an enumeration of the coordinate -- see the note above. -/")
        else:
            L.append("determined over the whole domain.  The pinning is not a decision and this is")
            L.append("not evidence for one -- it is the statement that what stays undetermined "
                     "stays")
            L.append("undetermined *here*, and nowhere else. -/")
        L.append(f"def pinned_{name} : Cfg := "
                 + _one_line_record("decidedSpec", {f: term for f, _, term in pin}))
        L.append(f"theorem {name} :")
        L.append(f"    determinedEverywhere (admits pinned_{name}) obsUniverse ctxUniverse legal "
                 "= true := by")
        L.append("  decide +kernel")
        L.append(f"#print axioms {name}")
        L.append("")

    # ---- or, when the specification turned out to have no model at all
    #
    # `decided_determined` fails in two opposite ways and the failure alone does not say which.
    # Too MANY admitted observations is an open coordinate, above.  Too FEW -- none, at a legal
    # context -- is a specification no implementation can satisfy, which happens when the prose
    # contradicts itself and the designer answers in favour of one side of the contradiction.
    # That is a result about the document, and the strongest form of one this framework can
    # produce, so it is stated as a theorem at a named context rather than left to be inferred
    # from a determinacy proof that did not close.
    if unsat_ctx:
        L.append("/-- There is a legal context at which the decided specification admits NO")
        L.append("observation. No implementation conforms to it, and no further round can make")
        L.append("one: the sentences the decisions above rest on contradict each other, and")
        L.append("`out/REPORT.md` names which. -/")
        L.append("theorem decided_admits_nothing :")
        L.append(f"    admitSet (admits decidedSpec) obsUniverse ({unsat_ctx}) = [] := by")
        L.append("  decide +kernel")
        L.append("#print axioms decided_admits_nothing")
        L.append("/-- ... and the context is one the specification's own assumptions allow. -/")
        L.append("theorem decided_admits_nothing_legal :")
        L.append(f"    legal ({unsat_ctx}) = true := by decide +kernel")
        L.append("#print axioms decided_admits_nothing_legal")
        L.append("")

    # ---- one refutation per rejected reading, at the witness that refuted it
    #
    # `decide +kernel` here, not bare `decide`, for the same reason `decided_determined` uses it:
    # the elaborator's own whnf carries every intermediate on the C stack, and a case whose `Ctx`
    # and `Obs` are LISTS rather than machine words exhausts even the 64 Mb `leanrun` asks for.
    # `realbench/aes_rcon` -- 38 contexts, 66 observations, a domain the compiled evaluator walks
    # in milliseconds -- aborted the whole file with "Stack overflow detected" on `disjointAt` at
    # a one-step context, taking the theorems ABOVE it down with it, since an aborted process
    # prints no `#print axioms` line at all.  The kernel closes the identical proposition.
    refs = _refutations(doc, findings, fields)
    ref_errs = [r["error"] for r in refs if r.get("error")]
    refs = [r for r in refs if not r.get("error")]
    for r in refs:
        L.append(f"/-- `{r['name']} := {r['tag']}` is ruled out: at the context the diagnosis")
        L.append("printed, everything `decidedSpec` admits, this reading forbids.  The other")
        L.append("half of the refutation is the reference's observation, in `out/REPORT.md`. -/")
        L.append(f"def rejected_{r['name']}_{r['tag']} : Cfg := "
                 + _one_line_record("decidedSpec", {r["field"]: r["value"]}))
        L.append(f"theorem legal_{r['name']}_{r['tag']} :")
        L.append(f"    legal ({r['ctx_lean']}) = true := by decide +kernel")
        L.append(f"#print axioms legal_{r['name']}_{r['tag']}")
        L.append(f"theorem refuted_{r['name']}_{r['tag']} :")
        L.append(f"    disjointAt (admits decidedSpec) (admits rejected_{r['name']}_"
                 f"{r['tag']}) obsUniverse ({r['ctx_lean']}) = true := by decide +kernel")
        L.append(f"#print axioms refuted_{r['name']}_{r['tag']}")
        L.append("")

    # ---- the extensional table: the specification as behaviour, not as a definition
    #
    # `emitDecided` prints the counts and `emitSweep` prints the contexts behind them, and step
    # 07 needs the second: `decided_determined` fails identically whether a context admits
    # several observations or none, and those mean opposite things.  The sweep is re-read to
    # find a legal context admitting NOTHING, and the file is then re-emitted proving
    # `decided_admits_nothing` there.
    #
    # This carries a name from the tree it came from, where a further step compared these lines
    # against a reference implementation.  That step is gone -- it is an evaluation, and this
    # half has no answer key -- so nothing here is compared against anything.
    L.append("-- The specification extensionally: one line per legal context.")
    L.append('#eval emitDecided case "decided" (admits decidedSpec)')
    L.append("#eval emitSweep case (admits decidedSpec)")
    return "\n".join(L) + "\n", ref_errs


_PRIMITIVE = {"Nat", "Int", "Bool", "String", "Char", "Fin", "UInt8", "UInt16", "UInt32"}

#: How many full pinnings of the open coordinates `gen_lean` will write theorems for.  Each one
#: is a `decide +kernel` over the whole context universe, so the product of two three-valued
#: coordinates is already nine sweeps of a domain that took seconds to search once.  Past this
#: the claim is dropped rather than made expensive: a case with that many open coordinates has a
#: bigger problem than the shape of its determinacy theorem.
MAX_PINNINGS = 12


def _constructors(partial_src: str, enum: str) -> list[str] | None:
    """The constructors of `inductive <enum>`, or None if there is no such declaration."""
    m = re.search(rf"(?ms)^inductive\s+{re.escape(enum)}\b(.*?)(?=^\S|\Z)", partial_src)
    if not m:
        return None
    return re.findall(r"(?m)^\s*\|\s*([A-Za-z_]\w*)", m.group(1)) or None


def _field_tags(partial_src: str, ftype: str) -> list[str] | None:
    """Every value a `Cfg` field of this type can take, as reading tags, or None if unbounded.

    Read off the field's declared TYPE rather than off `cfgPins_<name>`.  The two differ, and
    the difference is the whole point: `cfgPins_` is the menu stage 1 chose to offer the oracle,
    and a menu can be a sample.  The type is closed.  A claim quantified over the constructors
    of `Kwarmup` says "under every value this coordinate can hold"; the same claim quantified
    over an offered menu would say "under every value we happened to ask about", which is the
    `pinned_sampled` mistake the resolution step already refuses to make.
    """
    t = ftype.strip()
    if t.startswith("Option "):
        t = t[len("Option "):].strip()
    if t == "Bool":
        return ["0", "1"]
    if re.fullmatch(r"[A-Za-z_]\w*", t) and t not in _PRIMITIVE:
        return _constructors(partial_src, t)
    return None                                     # Nat and friends: no finite enumeration


def _menu_tags(partial_src: str, name: str) -> list[str] | None:
    """The reading tags of `cfgPins_<name>`, or None if the file declares no such menu.

    This is the OFFERED menu and not the coordinate's domain -- which is exactly why
    `_field_tags` reads the type instead, and why this is reached only where the type has no
    finite enumeration at all.  Every claim built on it is labelled with what it quantifies
    over, in the file and in the finding: see `_pinnings`.
    """
    m = re.search(rf"(?ms)^def cfgPins_{re.escape(name)}\s*:.*?:=(.*?)(?=^\S|\Z)", partial_src)
    if not m:
        return None
    return re.findall(r'\(\s*"([^"]*)"\s*,', m.group(1)) or None


def _menu_term(nm: str, field: str, tag: str) -> str:
    """The value `cfgPins_<nm>` pairs with `tag`, as a term -- looked up rather than transcribed.

    `((cfgPins_x.lookup "tag").getD defaultCfg).h_field`: Lean performs the lookup, so the value
    a pinning theorem names is the one the menu holds and not this file's copy of it.  Pulling
    the record literal out of `Partial.lean` with a regex is the alternative and it is worse in
    the way that matters here -- the entries are authored, they nest braces and span lines, and a
    transcription that drifted from the menu would yield a theorem that is still true and no
    longer about the reading it is named after.

    `getD defaultCfg` is unreachable: the tag came off this same menu and the `menu_<field>`
    theorem `gen_lean` writes beside the pinnings proves it is still there.  A default is written
    rather than a `panic!` so that the file elaborates far enough for that theorem to be the
    thing that reports the problem.
    """
    return f'((cfgPins_{nm}.lookup "{tag}").getD defaultCfg).{field}'


def _pinnings(partial_src: str,
              still_open: list[dict]) -> tuple[list[list[tuple]], str | None, list[str], int]:
    """Every full assignment of the open coordinates, or a reason there is no such list.

    Returns `(pinnings, why_not, sampled_fields, product)`.  Each pinning is a list of
    `(field, tag, lean_term)`, and the list is the cartesian product over the open fields -- so a
    theorem per pinning quantifies over the open coordinates *jointly*, which is what "the rest
    of the specification is determined" has to mean when two coordinates are open at once.

    `product` is the size of that product, and it is returned rather than inferred because a
    caller has to tell the two declines apart: too MANY pinnings to write is a round that settled
    little, and a field with no enumerable axis is a coordinate nothing here can quantify over at
    all.  It is `0` when the decline is the second kind, and when there is nothing open.

    `sampled_fields` names the coordinates whose axis came off `cfgPins_` rather than off the
    field's type.  A numerically-typed hole -- `h_dout_reset : Option Nat` over an eight-bit port
    -- has no finite enumeration, and before this fallback existed such a case got no pinning
    theorem at all, which meant `_attribute_indeterminacy` had nothing to corroborate the
    finding with and the step reported a broken emission where what had happened was that the
    prose left a value unstated.  `rtllm/serial2parallel` round 1 is the case.

    What the fallback does NOT do is upgrade the claim.  Each theorem is still exactly true --
    it pins named values and proves determinacy at them -- but the *set* of them no longer
    covers the coordinate's domain, so it locates the indeterminacy only as far as the menu
    reaches.  That difference is written into the emitted file and into the finding rather than
    left for a reader to infer from the field's type.
    """
    if not still_open:
        return [], "nothing is open", [], 0
    axes, sampled = [], []
    for o in still_open:
        nm = o.get("name") or re.sub(r"^[hc]_", "", o.get("field", ""))
        menu, tags = False, _field_tags(partial_src, o.get("type", ""))
        if not tags:
            tags = _menu_tags(partial_src, nm)
            if tags:
                menu = True
                sampled.append(o["field"])
        if not tags:
            return [], (f"`{o['field']}` has type {o.get('type')!r}, which has no finite "
                        f"enumeration, and `Partial.lean` declares no `cfgPins_{nm}` menu to "
                        f"quantify over instead, so there is no list of pinnings"), [], 0
        vals = []
        for tag in tags:
            # A tag off the MENU is not rendered as a term of the field's type, and asking
            # `_lean_reading` to do it is how this fallback used to defeat itself.  That function
            # turns a reading's name into a value -- `Kout_phase.next_cycle`, `some 3` -- which it
            # can only do where the name *is* the value's spelling.  The menu is reached precisely
            # where it is not: `h_out_of_decade_next : Option (List Nat)` takes its readings from
            # `cfgPins_out_of_decade_next` and they are called `wrap_at_or_above_9`,
            # `clamp_to_nine` -- names of six-element maps, not terms of the type.  So
            # `_lean_reading` gave the refusal it is right to give, `_pinnings` returned it as a
            # decline, and the case got no pinning theorems at all -- on a coordinate the menu
            # fallback exists to handle.
            #
            # It went unseen because the fallback had only ever run on `rtllm/serial2parallel`'s
            # `h_dout_reset : Option Nat`, whose menu tags are numerals -- and those
            # `_lean_reading` renders correctly by coincidence, through the branch that lets a
            # digit stand for itself.  `verilogeval/Prob067_countslow` is the first menu whose
            # tags are names, and it failed the step.
            if menu:
                term = _menu_term(nm, o["field"], tag)
            else:
                term, err = _lean_reading(o.get("type", ""), tag)
                if err:
                    return [], f"`{o['field']}`: {err}", [], 0
            vals.append((o["field"], tag, term))
        axes.append(vals)
    total = 1
    for a in axes:
        total *= len(a)
    if total > MAX_PINNINGS:
        return [], (f"{total} full pinnings of {len(axes)} open coordinate(s) is more than "
                    f"MAX_PINNINGS={MAX_PINNINGS}"), [], total
    out = [[]]
    for a in axes:
        out = [p + [v] for p in out for v in a]
    return out, None, sampled, total



def _lean_reading(ftype: str, tag: str) -> tuple[str, str | None]:
    """A reading's tag, as a Lean term of the field's declared type.

    The oracle and the decision record both name a reading the way the *specification* does --
    `next_cycle`, `result_hold`, `0` -- because that is the vocabulary a reader of the prose
    has.  Lean needs `Kout_phase.next_cycle` and `some Kdout_idle.result_hold`.  The
    qualification is read off the field's declared type rather than repeated in the decision
    record: a decision that had to spell its own Lean namespace could spell it wrong, and an
    unqualified constructor does not fail loudly here -- the `def` takes a `sorryAx` body and
    the first thing anyone sees is `decide` failing two theorems further down.
    """
    t, opt = ftype.strip(), False
    if t.startswith("Option "):
        opt, t = True, t[len("Option "):].strip()
    if t == "Bool":
        # The one type where the numeric spelling is the natural one, and the one where it does
        # not elaborate.  `0` and `1` are how the prose, the diagnosis and the resolution all
        # name a one-bit value, but `1 : Bool` is not a term: the numeral falls through to
        # `OfNat`, finds no instance, and the `def` is *admitted* with a `sorryAx` body rather
        # than rejected -- which is precisely the silent failure this function exists to prevent,
        # reached through the branch that lets a digit stand for itself.
        v = {"0": "false", "1": "true", "false": "false", "true": "true"}.get(tag, "")
        if not v:
            return "", (f"reading {tag!r} cannot be written as a term of type {ftype!r}: a "
                        f"one-bit reading is spelled 0 or 1")
    elif re.fullmatch(r"-?0\d+", tag):
        # A numeral with a leading zero is a bit-pattern LABEL -- `000`, `010`, `101` -- not a
        # term.  On a numeric field Lean reads it as decimal: `010` becomes ten and `101` becomes
        # a hundred and one, neither of which is a value the coordinate's domain contains, so the
        # configuration named after the reading admits nothing anywhere.  The theorems about it
        # then pass VACUOUSLY -- `disjointAt` is trivially true of a configuration with no models,
        # so `refuted_<tag>` elaborates, prints no axioms, and claims to have ruled out a reading
        # it never mentioned.  On an inductive field it is not a constructor name at all and the
        # `def` takes a `sorryAx` body.  Both are silent wrong answers, so both are refused here.
        return "", (f"reading {tag!r} cannot be written as a term of type {ftype!r}: a numeral "
                    f"with a leading zero is a bit-pattern label rather than a term.  On a "
                    f"numeric field Lean reads it as decimal ({tag} = {int(tag)}), which is not "
                    f"the value the reading names, and the theorems about it then pass vacuously; "
                    f"on an inductive field it is not a constructor name.  Spell it 0b{tag} in "
                    f"the extraction's tags and in `cfgPins_` -- Lean parses a `0b` literal and "
                    f"this function passes it through -- or use the decimal value")
    elif re.fullmatch(r"-?\d+", tag) or "." in tag or t in _PRIMITIVE:
        v = tag
    elif re.fullmatch(r"[A-Za-z_]\w*", t):
        v = f"{t}.{tag}"
    else:
        return "", (f"reading {tag!r} cannot be written as a term of type {ftype!r}: the type "
                    f"is not a plain inductive and the tag is not already qualified")
    return (f"some {v}" if opt else v), None


def _refutations(doc: dict, findings: list[dict], fields: list[dict]) -> list[dict]:
    """A rejected reading, paired with the context that separated it from the decided one.

    The context comes from the *diagnosis*, not from the decision: the witness a decision names
    is a finding id, and the finding is where the term was printed.  Taking it from anywhere
    else would let the theorem be about a different input than the one reported, which is the
    failure `diagnose.py`'s two-pass shape exists to prevent.

    Both kinds of question are covered.  A rejected *fork* reading takes its context from the
    `difference` finding that separated it FROM THE READING THE DECISION KEPT; a rejected *hole*
    value takes its context from the `hole` finding that reported the coordinate free, which is
    the context at which the admitted set had more than one element and so the one at which
    pinning it can be shown to matter.

    Which pair is not a detail.  The theorem this feeds is about the decided reading --
    `disjointAt (admits decidedSpec) (admits rejected_<tag>)` -- and a fork with n readings is
    diagnosed as all n(n-1)/2 pairs, so the first finding that merely *mentions* `tag` is
    usually its comparison against some third reading.  At that context the rejected reading and
    the kept one can agree on every observation, and then the proposition is false: `decide`
    says so, step 07 admits the theorem with a `sorryAx`, and a case that answered its question
    correctly fails on the certificate.  `realbench/sd_rx_fifo` (`next_edge_any` taken at its
    context against `same_edge`) and `realbench/sd_controller_wb` (`arg_write_level` at its
    context against `arg_access_level`, a read of `cmd_arg` that neither reading raises
    `int_busy` on) both failed exactly there.  The pair against `resolved_to` is preferred; the
    old any-mention search stays as the fallback, for a decision whose kept reading the
    diagnosis never compared this tag with directly.
    """
    ftype = {f["field"]: f.get("type", "") for f in fields}
    by_choice: dict[str, list[dict]] = {}
    by_hole: dict[str, list[dict]] = {}
    for f in findings:
        if f.get("query") == "difference" and f.get("separated") and f.get("ctx_lean"):
            by_choice.setdefault(f["choice"], []).append(f)
        elif f.get("query") == "hole" and f.get("ctx_lean"):
            by_hole.setdefault(f["hole"], []).append(f)
    out = []
    for d in doc.get("decisions", []):
        kind, name, field = d.get("kind"), d.get("name"), d.get("cfg_field")
        if kind not in ("choice", "hole") or not field:
            continue
        kept = d.get("resolved_to")
        for tag in d.get("rejected", []):
            if kind == "choice":
                pairs = by_choice.get(name, [])
                ctx = (next((f["ctx_lean"] for f in pairs
                             if {f.get("a"), f.get("b")} == {tag, kept}), None)
                       or next((f["ctx_lean"] for f in pairs
                                if tag in (f.get("a"), f.get("b"))), None))
            else:
                ctx = next((f["ctx_lean"] for f in by_hole.get(name, [])), None)
            if ctx is None:
                continue
            value, err = _lean_reading(d.get("cfg_enum") or ftype.get(field, ""), tag)
            out.append({"name": name, "tag": tag, "ctx_lean": ctx, "field": field,
                        "value": value,
                        "error": (f"decision {name!r}: {err}" if err else None)})
    return out



def standalone(decided_src: str, partial_src: str, leanspec_src: str) -> str:
    """The same specification as one self-contained file.

    `import Partial` and `import LeanSpec` are dropped and their sources spliced in, in
    dependency order.  Nothing else is rewritten: the point of the file is that a reader can
    check it says the same thing as the three-file version by reading it.
    """
    strip = lambda s: re.sub(r"(?m)^\s*(import\s+\w+|open\s+LeanSpec)\s*$\n?", "", s)
    return (
        "-- GENERATED by leanspec/emit.py -- do not edit.\n"
        "--\n"
        "-- `LeanSpec.lean` + the case's `Partial.lean` + the decided section, concatenated\n"
        "-- into one file so that the decided specification and its proofs can be elaborated\n"
        "-- with no import path and no knowledge of this directory's layout:\n"
        "--\n"
        "--     lean DecidedSpec.standalone.lean\n"
        "--\n"
        "-- The three-file version is the one the pipeline runs; this one is the artifact.\n\n"
        + leanspec_src.rstrip() + "\n\n"
        + "open LeanSpec\n\n"
        + "/-! # The case's partial semantics (from `sandbox/Partial.lean`) -/\n\n"
        + strip(partial_src).strip() + "\n\n"
        + "/-! # The decided specification -/\n\n"
        + strip(decided_src).strip() + "\n")


def elaborate(workdir: str, decided_src: str, standalone_src: str,
              partial_src: str) -> dict:
    """Write both files, elaborate both, and report what the axioms say.

    The three-file version is elaborated against a freshly compiled `Partial.olean` in the same
    directory, for the same reason `diagnose.py` recompiles: a stale olean would prove a
    theorem about the previous round's semantics and print this round's file name beside it.
    """
    os.makedirs(workdir, exist_ok=True)
    pp = os.path.join(workdir, "Partial.lean")
    with open(pp, "w") as f:
        f.write(partial_src)
    pres = leanrun.run(pp, emit_olean=True)
    if not pres["ok"]:
        return {"ok": False, "where": "Partial.lean", "lean": leanrun.summarize(pres),
                "errors": pres["errors"][:20], "log": pres["log"]}

    dp = os.path.join(workdir, "DecidedSpec.lean")
    with open(dp, "w") as f:
        f.write(decided_src)
    dres = leanrun.run(dp)

    sp = os.path.join(workdir, "DecidedSpec.standalone.lean")
    with open(sp, "w") as f:
        f.write(standalone_src)
    sres = leanrun.run(sp)

    admitted = sorted(set(dres["admitted"]) | set(sres["admitted"]))
    return {
        "ok": dres["ok"] and sres["ok"],
        "decided": {"lean": leanrun.summarize(dres), "axioms": dres["axioms"],
                    "errors": dres["errors"][:20], "sweep": [f for f in dres["findings"]
                                                             if f.get("query") == "sweep"],
                    "decided_line": next((f for f in dres["findings"]
                                          if f.get("query") == "decided"), None)},
        "standalone": {"lean": leanrun.summarize(sres), "axioms": sres["axioms"],
                       "errors": sres["errors"][:20]},
        "admitted": admitted,
        "log": dres["log"],
        "standalone_log": sres["log"],
    }


# ------------------------------------------------------- the waveforms, and the question list
#
# A finding is a claim about *behaviour*, and it has been readable here only as JSON: a context
# term, two lists of admitted observations, a certificate saying they are disjoint.  That is
# checkable and it is not legible.  The same three things drawn as a waveform are:
#
#     the stimulus       — what the module is driven with
#     one band per reading — everything that reading allows the outputs to do under it
#     the measured trace — what the designer said the module does
#
# and the question the whole framework is built to ask is then visible as a picture: the two
# bands are drawn side by side, the step where they cannot both be right is marked, and the
# measured row lands inside exactly one of them.
#
# A *band* rather than a trace, and this is the part that would be wrong if it were simplified.
# A reading is not one behaviour.  The other coordinates of `Cfg` are still open while this one
# is being asked about, so a reading admits a set of observations, and drawing one of them as
# "what this reading predicts" would be putting a value on the page that nothing chose.  Where
# the admitted observations disagree at a step, the cell shows the set.  Where they agree, the
# cell is that value -- and a column where both bands are single-valued and different is exactly
# what `disjointAt` proved.

_MAX_CELL = 18


def _steps_of(trace) -> list[dict]:
    """A trace as a list of per-step signal maps.

    Witnesses carry `{"steps": [...]}`, because that is the shape `Ctx`/`Obs` serialise to; the
    oracle's recorded observation is the bare list.  Both arrive here.

    A step may be `null`, and that is not a malformed trace: `oracle._project` writes one wherever
    the menu's focus keeps nothing, so the behaviour the designer picked asserts the coordinates
    the question was about and stays silent everywhere else.  `refine._matches` has always read a
    `null` step as a don't-care; the three readers below iterated it and step 08 died with
    `'NoneType' object is not iterable` on the first case that had a projected menu.  Normalising
    here rather than at each use keeps the length -- a step nobody asserted anything at is still a
    step -- so `_band` still draws it as a column, empty, which is what `·` means.
    """
    steps = trace.get("steps") if isinstance(trace, dict) else trace
    return [st or {} for st in (steps or [])]


def _signals(traces: list) -> list[str]:
    """Signal names, in the order the traces first mention them."""
    seen: list[str] = []
    for t in traces:
        for st in _steps_of(t):
            for k in st:
                if k not in seen:
                    seen.append(k)
    return seen


def _band(traces: list) -> dict[str, list[list]]:
    """Per signal, per step, the distinct values these traces show."""
    sigs, out = _signals(traces), {}
    n = max((len(_steps_of(t)) for t in traces), default=0)
    for s in sigs:
        out[s] = [[] for _ in range(n)]
    for t in traces:
        for i, st in enumerate(_steps_of(t)):
            for s in sigs:
                if s in st and st[s] not in out[s][i]:
                    out[s][i].append(st[s])
    return out


def _cell(vals: list) -> str:
    if not vals:
        return "·"
    if len(vals) == 1:
        return str(vals[0])
    s = "{" + ",".join(str(v) for v in vals) + "}"
    return s if len(s) <= _MAX_CELL else s[:_MAX_CELL - 2] + "…}"


def _decisive(a: dict[str, list[list]], b: dict[str, list[list]]) -> tuple[int, str] | None:
    """The first step at which the two bands cannot both be right, and the signal that does it.

    "Cannot both be right" is set-disjointness at one step, which is strictly stronger than the
    two bands merely differing there.  A step where they differ but overlap eliminates nothing:
    the answer can land in the intersection and both readings survive it.
    This is the same distinction `queryDiscriminating` makes in Lean, computed here only so the
    drawing can point at the column.
    """
    for i in range(min((max((len(v) for v in d.values()), default=0)) for d in (a, b))):
        for s in a:
            if s in b and a[s][i] and b[s][i] and not ({repr(v) for v in a[s][i]}
                                                       & {repr(v) for v in b[s][i]}):
                return i, s
    return None


_VIO_SIDE = {
    "definitions": ("the definitions stand", "the guarantee is wrong"),
    "property": ("the guarantee stands", "the definitions are wrong"),
}


def _vio_answer(w: dict, r: dict) -> str:
    """What one adjudication of a contradiction settled, as a sentence.

    Not routed through `answer()` above, which is written for a menu of behaviours: every one of
    its branches explains the verdict in terms of a waveform the designer picked, and here the
    designer picked a sentence.  `decided` would have printed "the waveform the designer picked
    is admitted by `definitions`" -- true of the plumbing and false of what happened.
    """
    prop = w.get("property") or ""
    if not r:
        return f"— The contradiction at `{prop}` was not put to the designer."
    out = r.get("outcome")
    said = (r.get("designer_said") or "").strip().rstrip(".")
    tail = f' They said: "{said}."' if said else ""
    if out == "decided":
        tag = next((k.split(":", 1)[-1] for k in (r.get("kept") or [])), "?")
        keep, drop = _VIO_SIDE.get(tag, (f"`{tag}`", "the other sentence"))
        return (f"**{tag}** — {keep}, and {drop}. The repair is a rewrite of the sentence the "
                f"designer disowned; the decision that carries it is in "
                f"[`REPORT.md`](REPORT.md), and whether it worked is a question only the next "
                f"round's property check can answer.{tail}")
    if out == "outside":
        return ("***neither*** — the designer rejected both sentences. That is a stronger "
                "finding than the contradiction itself: not only can the two not both stand, "
                "the fault is in neither of them as stated. Nothing here invents the sentence "
                f"they meant instead; it is reported and left open.{tail}")
    return ("*unadjudicated* — the contradiction was put to the designer and no sentence was "
            "named, so both are still in the specification and both cannot hold. This is an "
            f"unanswered question, not a settled one.{tail}"
            + (f" ({r.get('detail')})" if r.get("detail") else ""))


def _bands(w: dict) -> list[tuple[str, list]]:
    """`(label, traces)` per candidate reading of the question this witness is about.

    A hole's `predicted` map also carries the other holes' bands -- the diagnosis evaluates the
    whole configuration at once -- so it is filtered to the one this witness asks about.  Drawing
    the others would put a second question's readings under this question's heading.
    """
    pred = w.get("predicted") or {}
    if w.get("kind") == "violation":
        # Not readings of a fork.  A violated property has one reading and the trouble is what
        # that reading admits, so the single band is the admit set itself and the caption below
        # says which of the two sentences it belongs to.  Drawing it at all is the point: the
        # designer is being asked which sentence to give up, and one of them is a waveform.
        return [("your definitions, at this input", w.get("admits") or [])]
    if w.get("choice"):
        return [(f"{w['choice']} = {t}", pred.get(f"{w['choice']}:{t}") or [])
                for t in (w.get("candidates") or [])]
    h = w.get("hole")
    pre = f"hole:{h}="
    return [(f"{h} = {k[len(pre):]}", pred[k]) for k in sorted(pred) if k.startswith(pre)]


def waveform(w: dict, observed=None) -> str:
    """The witness drawn: stimulus, one band per reading, the measured trace, the column that
    separates them."""
    ctx = w.get("ctx") or {}
    n = len(_steps_of(ctx))
    if not n:
        return ""

    rows: list[tuple[str, object]] = []

    def section(title: str) -> None:
        rows.append(("\x00", title))

    def band_rows(traces: list) -> None:
        b = _band(traces)
        for s in _signals(traces):
            rows.append((s, [_cell(b[s][i]) if i < len(b[s]) else "" for i in range(n)]))

    # A contradiction witness has no readings to tell apart -- it is a context at which the prose
    # admits nothing -- so the stimulus caption says what the input is *for* instead of naming a
    # separation that is not there.  A violation witness has one band and no separation either,
    # and the reverse problem: the prose admits something here that another sentence of the same
    # prose forbids.
    section("stimulus — the legal input at which your definitions and your guarantee disagree"
            if w.get("kind") == "violation" else
            "stimulus — the cheapest legal input that tells the readings apart"
            if _bands(w) else
            "stimulus — the cheapest legal input at which the prose admits nothing")
    band_rows([ctx])

    bands = _bands(w)
    for label, traces in bands:
        section(f"if  {label}"
                + (f"   ({len(traces)} observation(s) this reading admits)" if traces else ""))
        band_rows(traces)

    dec = None
    if len(bands) >= 2:
        dec = _decisive(_band(bands[0][1]), _band(bands[1][1]))
    if dec:
        rows.append(("\x01", [("^^^" if i == dec[0] else "") for i in range(n)]))

    if observed:
        # The chosen waveform is projected onto the menu's focus, so it asserts the coordinates
        # the question turned on and stays blank everywhere else.  The bands above it are not
        # projected, so this row is legitimately sparser than they are -- and a reader who takes a
        # `·` here for "the designer said nothing happens" reads a claim into a silence, which is
        # the opposite of what the projection means.  Said only when it is true, so a menu that
        # was never reduced draws exactly the row it always drew.
        def coords(traces: list) -> set:
            return {(s, i) for t in traces
                    for i, st in enumerate(_steps_of(t)) for s in st}
        partial = bool(coords([t for _, tr in bands for t in tr]) - coords([observed]))
        # And on a violation the bottom row is not a choice at all.  It is the one behaviour out
        # of the admitted set that the guarantee rejects, and captioning it "the waveform the
        # designer picked" would attribute the specification's own defect to the person who was
        # shown it -- in a document whose whole purpose is to keep those two apart.
        section("the behaviour the guarantee rejects" if w.get("kind") == "violation" else
                "chosen — the waveform the designer picked"
                + ("   (`·` — a coordinate this question did not ask about)" if partial else ""))
        band_rows([observed])

    # ---- lay it out
    lab = max((len(r[0]) for r in rows if r[0] not in ("\x00", "\x01")), default=8)
    lab = max(lab, len("separates"))
    wid = [max([len(f"t{i}")] + [len(r[1][i]) for r in rows
                                 if r[0] != "\x00" and i < len(r[1])]) for i in range(n)]
    L = ["  " + " " * lab + "  " + "  ".join(f"t{i}".rjust(wid[i]) for i in range(n))]
    for name, val in rows:
        if name == "\x00":
            L.append(f"  {val}")
            continue
        if name == "\x01":
            L.append(f"  {'separates'.ljust(lab)}  "
                     + "  ".join(str(val[i]).center(wid[i]) for i in range(n)).rstrip())
            continue
        L.append(f"  {name.ljust(lab)}  "
                 + "  ".join(str(val[i]).rjust(wid[i]) for i in range(n)))
    out = ["```text", *L, "```", ""]
    if dec:
        i, s = dec
        a, b = _band(bands[0][1]), _band(bands[1][1])
        out += [f"At **t{i}** the two bands are disjoint on `{s}`: "
                f"`{bands[0][0]}` allows {_cell(a[s][i])} and `{bands[1][0]}` allows "
                f"{_cell(b[s][i])}, and no value is in both. That column is the whole question; "
                f"the rest of the trace is there to reach it.", ""]
    elif len(bands) >= 2:
        a, b = _band(bands[0][1]), _band(bands[1][1])
        # A reading that admits nothing overlaps with nothing, and saying "the bands overlap"
        # of it is the opposite of true.  It arises whenever a candidate is the literal
        # conjunction of sentences that contradict each other -- `square_wave`'s `as_written`
        # keeps both of the two thresholds the prose gives for one compare, `edge_detect`'s
        # keeps the pulse and the hold at once -- and it is the shape the diagnosis reports as
        # a repair rather than an ambiguity.  `_decisive` cannot name a column for it because
        # it looks for a step where both bands are non-empty and disjoint, and an empty band is
        # never non-empty; that is right, since there is no *one* column doing the work.  What
        # is wrong is falling through to the overlap sentence, so the empty case is said first.
        dead = [lb for lb, tr in bands[:2] if not tr]
        if dead:
            live = [lb for lb, tr in bands[:2] if tr]
            out += [f"`{dead[0]}` admits no observation at all here"
                    + (f", while `{live[0]}` admits {len(bands[0][1] or bands[1][1])}" if live
                       else " and neither does the other")
                    + ". The two are disjoint at every column of this context, and trivially so: "
                      "whatever the designer picks, it cannot be a trace the empty reading "
                      "allows. That is what makes this a repair and not an ambiguity — the "
                      "question is not which of two behaviours the prose meant but whether one "
                      "of its readings describes any behaviour at all.", ""]
        else:
            out += ["The two bands are identical here — every observation one reading admits, "
                    "the other admits too — so this context cannot decide the question."
                    if a == b else
                    "The bands overlap at every step of this context: at each column there is a "
                    "value both readings allow. A measurement here can therefore land inside "
                    "both, which is why difference alone is not what the search looks for.", ""]
    return "\n".join(out)


def _basis_ids(ext: dict, src: dict) -> list[str]:
    """The clause ids this question rests on.

    A choice carries `basis` -- the clause ids whose readings together make it a question.  A
    hole usually does not, because a hole is the *absence* of a sentence; what it has instead is
    the clause that claimed it, which the extraction schema requires to exist in both
    directions.  Both are followed, so a question is never printed without the prose it came
    from.
    """
    ids = list(src.get("basis") or [])
    for c in ext.get("clauses", []):
        if src.get("id") and src["id"] in (c.get("choice_id"), c.get("hole_id")) \
                and c.get("id") not in ids:
            ids.append(c["id"])
    return ids


def _quote(ext: dict, src: dict) -> list[str]:
    ids = _basis_ids(ext, src)
    out = []
    for c in ext.get("clauses", []):
        if c.get("id") in ids:
            sp = c.get("span") or [0, 0]
            out.append(f"* **{c['id']}** (bytes {sp[0]}–{sp[1]}) — “{c.get('text', '').strip()}”")
    return out


_LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def _options(w: dict, src: dict, is_hole: bool) -> list[str]:
    """The question as a lettered option list, with a line saying what the option set *is*.

    Every question this framework asks is multiple choice -- the oracle is handed N pinned
    configurations and reports which survive, never a blank -- so the options are what the
    question *is*, and printing them as a bulleted afterthought understated that.

    The second thing a reader needs is whether the options exhaust the possibilities, because it
    decides what a single survivor is worth.  A fork's options come from an `inductive` whose
    constructors `schema.check_partial` cross-checks, so they are closed by construction.  A
    hole's may be an enumeration or a sample, and the difference is only knowable from what
    stage 1 declared, so an undeclared one says so rather than implying either.
    """
    cands = list(src.get("candidates") or [])
    if not cands:                        # a hole whose values live only in `cfgPins_`
        cands = [{"tag": lab.split(" = ")[-1]} for lab, _t in _bands(w)]
    L = []
    if not is_hole:
        L.append(f"**The options.** Closed — a reading of the prose is one of these {len(cands)}, "
                 f"cross-checked against the constructors of `K{w.get('choice')}`.")
    else:
        dom = schema.domain_of(src)
        n, size = len(cands), dom.get("size")
        if dom["status"] == schema.CLOSED:
            L.append(f"**The options.** Closed — these {n} are the whole domain{_why(dom)}.")
        elif dom["status"] == schema.SAMPLED:
            L.append(f"**The options.** A sample — {n} of the {size} values this coordinate can "
                     f"take{_why(dom)}. “None of the above” is possible, so these options can "
                     f"show the coordinate is *free*, but a single survivor would not prove it "
                     f"is the answer.")
        else:
            L.append(f"**The options.** Domain undeclared — stage 1 recorded no size for this "
                     f"coordinate, so whether these {n} exhaust the possibilities is not known. "
                     f"A single survivor is carried with that caveat rather than as a fact.")
    L.append("")
    for i, c in enumerate(cands):
        rd = c.get("reading", "")
        L.append(f"* **{_LETTERS[i] if i < 26 else i + 1}. `{c.get('tag')}`**"
                 + (f" — {rd}" if rd else ""))
    return L


def _why(dom: dict) -> str:
    return f" ({dom['why']})" if dom.get("why") else ""


def _domain_cell(src: dict, is_hole: bool, n: int) -> str:
    """The summary table's domain column: what the option set claims to be, in three characters
    plus a fraction."""
    if not is_hole:
        return f"closed {n}/{n}"
    dom = schema.domain_of(src)
    if dom["status"] == schema.CLOSED:
        return f"closed {n}/{n}"
    if dom["status"] == schema.SAMPLED:
        return f"**sample {n}/{dom.get('size')}**"
    return "*undeclared*"


def merge_extractions(exts: list[dict]) -> dict:
    """One extraction covering every round, for the readers that need the whole run.

    A round does not add to the extraction, it *subtracts* from it: `pipeline._advance` removes
    an answered question from `choices`/`holes` and strips the `choice_id`/`hole_id` attribution
    off the clauses that raised it, because from the next round's point of view that question is
    no longer open.  Correct for the next round, and useless for anything that has to describe
    the run: the last round's extraction of a four-round case has three of its four questions
    missing and no record of which sentences they came from.

    So the roster comes from the *first* extraction that mentions a name, and the `domain`
    declaration from the *last*.  Those are two different moments on purpose: the roster is what
    was asked, and a later round can enumerate a domain an earlier one left unstated -- which is
    exactly what `rtllm/parallel2serial` round 4 did, and reading its declaration from round 1
    reported the widened menu as undeclared.

    A description a later round rewrote is read from the last round too, for the same reason and
    with a sharper one behind it: what a hole leaves unsaid is a claim about the *current*
    specification, and closing a question can falsify it.  `edge_detect`'s `reset_out` was
    described in round 1 as "the value the *hold* reading starts accumulating from"; round 1 then
    refuted `hold`, and round 2 rewrote the sentence.  Rendering the first wording in the
    deliverable would explain a hole the document reports as open in terms of a reading the same
    document reports as dead.

    Order is oldest-first.  An empty list gives an empty extraction rather than raising, so a
    caller with no chain behind it still renders.
    """
    if not exts:
        return {"clauses": [], "choices": [], "holes": [], "ports": [], "deferred": []}
    out = dict(exts[-1])                       # scalars and anything not merged below
    for key, ident in (("clauses", "id"), ("choices", "name"), ("holes", "name")):
        first: dict = {}
        for e in exts:
            for item in e.get(key) or []:
                k = item.get(ident)
                if k is None:
                    continue
                if k not in first:
                    first[k] = dict(item)
                else:
                    # The roster entry stays round 1's -- it is the one that still carries the
                    # attribution -- but a declaration made later is the current one, and so is
                    # a description a later round revised.
                    for f in ("domain", "candidates", "candidate_domain",
                              "missing", "why_required", "question", "why"):
                        if f in item:
                            first[k][f] = item[f]
        out[key] = list(first.values())
    return out


def questions_markdown(case_name: str, ext: dict, witnesses: list[dict],
                       resolutions: list[dict]) -> str:
    """`out/QUESTIONS.md` — every question the prose left open, and what the designer answered.

    Written by step 08, which is sealed.  That is not a contradiction and it is worth being
    explicit about: the answers here are read out of step 06's recorded resolutions, which are
    already in this step's input document.  Step 08 does not open the oracle to write this
    file; it reads what the step that was allowed to opened.

    The order is the order the framework works in, and it is the point of the file: the question
    is stated, the readings are stated, the stimulus that separates them is stated, and only
    then is the answer given.  A specification document that shows the answer first cannot be
    checked -- the reader has no way to tell whether the question had two answers or one.

    `witnesses` and `resolutions` span every round, so a question asked twice appears twice --
    which is a thing that happens and is worth seeing: `parallel2serial/reset_data` was asked in
    round 1 against three of the sixteen 4-bit patterns and again in round 4 against all
    sixteen, and the two rows do not say the same thing.  They are matched on `(round, id)` and
    not on `id` alone, or the later asking would silently answer the earlier one.
    """
    by_w = {(r.get("round"), r.get("witness")): r for r in resolutions}
    by_id = {r.get("witness"): r for r in resolutions}      # pre-round documents
    choices = {c["name"]: c for c in ext.get("choices", [])}
    holes = {h["name"]: h for h in ext.get("holes", [])}

    def res_of(w: dict) -> dict | None:
        return by_w.get((w.get("round"), w.get("id"))) or (
            by_id.get(w.get("id")) if w.get("round") is None else None)

    def title(w: dict) -> str:
        if w.get("hole") in holes:
            return holes[w["hole"]].get("missing", "").rstrip(".")
        return "which reading of the prose holds"

    def mine(w: dict, tags) -> list:
        """Only the tags that belong to *this* question's coordinate.

        Stage 3 evaluates every predicate at every context it emits, so one witness's `kept`,
        `eliminated` and `consistent` carry the other coordinates' tags too: a fork asked while a
        hole is still open comes back having eliminated seven of the hole's eight values as well
        as its own losing reading.  Printed unscoped, `adder_pipe_64bit`'s Q1 read "admitted by
        `enable_discipline:shift` and forbidden by `enable_discipline:gate`, `1`, `2`, `4` ..." --
        inviting the reader to take `1`, `2`, `4` for readings of `enable_discipline`, which they
        are not.  They are the latency's, and the latency has its own row two paragraphs down.

        This is the rendering half of the scoping `refine._resolve` does when it decides the
        outcome; the two have to agree or the verdict and the sentence explaining it are computed
        over different sets.  Nothing is hidden by it: every coordinate a witness happened to
        settle is a question in its own right, with its own options, its own separating column and
        its own answer.
        """
        if w.get("hole"):
            pre = "hole:" + w["hole"]
            return [t for t in tags if t == pre or t.startswith(pre + "=")]
        if w.get("choice"):
            pre = w["choice"] + ":"
            return [t for t in tags if t.startswith(pre)]
        return list(tags)

    def answer(w: dict) -> tuple[str, str]:
        r = res_of(w)
        if not r:
            return "—", "This question was not asked."
        out = r.get("outcome")
        kept = [k for k in mine(w, r.get("kept") or []) if "=" in k or ":" in k]
        # A hole's eliminated options arrive as prediction tags -- `hole:dout_idle=result_hold`.
        # The survivor beside them is printed bare, and printing the loser with its plumbing
        # attached invites the reader to think the two are different kinds of thing.
        elim = [e.split("=", 1)[-1] if e.startswith("hole:") else e
                for e in mine(w, r.get("eliminated") or [])]
        if out == "decided":
            tag = (kept[0].split(":")[-1] if kept else "?")
            return f"**{tag}**", (
                f"The waveform the designer picked is admitted by `{kept[0] if kept else '?'}` "
                f"and forbidden by {', '.join('`' + e + '`' for e in elim)}, so the question is "
                f"settled and the losing reading is ruled out at the context above.")
        if out == "outside":
            return "*none of these*", (
                "The designer rejected every waveform offered. The menu at this context is "
                "exactly the union of what the readings admit there, so \"none of these\" "
                "refutes all of them at once: the fault is not that the prose is ambiguous but "
                "that no reading of it is right. That is a finding about the specification, and "
                "it is reported rather than resolved — nothing here may invent the behaviour the "
                "designer meant instead.")
        if out == "pinned":
            vals = r.get("pinned_to") or []
            return f"**{', '.join(map(str, vals))}**", (
                f"The observation pins the hole to {', '.join('`' + str(v) + '`' for v in vals)}"
                + (f", eliminating {', '.join('`' + e + '`' for e in elim)}" if elim else "")
                + ", and the options were the whole domain, so there is nothing else it could "
                  "have been.")
        if out == "pinned_undeclared":
            vals = r.get("pinned_to") or []
            return f"**{', '.join(map(str, vals))}** *(domain undeclared)*", (
                f"One option survived — {', '.join('`' + str(v) + '`' for v in vals)}"
                + (f", eliminating {', '.join('`' + e + '`' for e in elim)}" if elim else "")
                + ". Stage 1 recorded no size for this coordinate, so whether the options "
                  "exhausted it is not known: this is one survivor *among the values offered*, "
                  "and it is carried with that caveat rather than as a proven value.")
        if out == "pinned_sampled":
            vals, dm = r.get("pinned_to") or [], r.get("domain") or {}
            return "*not settled*", (
                f"One option survived — {', '.join('`' + str(v) + '`' for v in vals)} — but the "
                f"options were {dm.get('offered')} of {dm.get('size')}, a sample rather than the "
                f"domain. The value the designer holds need never have been offered, so a "
                f"single survivor is not an answer and the question stays open.")
        if out == "partial":
            vals = r.get("pinned_to") or kept
            n = len(mine(w, (r.get("consistent") or {}).keys()))
            return (f"*narrowed to {', '.join('`' + str(v) + '`' for v in vals)}*", (
                f"The observation ruled some options out and not others: "
                f"{', '.join('`' + str(v) + '`' for v in vals)} survive"
                + (f" and {', '.join('`' + e + '`' for e in elim)} are eliminated" if elim else "")
                + f". That is evidence and not silence — the menu is smaller than the "
                  f"{n} options it started with — but it does not name a value, so the question "
                  f"is carried forward with the survivors rather than closed on one of them."))
        if out == "silent":
            vals = r.get("pinned_to") or kept
            listed = ", ".join("`" + str(v) + "`" for v in vals)
            if r.get("verdict") == "any":
                return "*any of them*", (
                    f"The designer declared the choice free: {listed} are all acceptable. That "
                    f"is an answer and not a shrug — it says the specification may leave this "
                    f"coordinate open — but it names no value, so the coordinate is carried into "
                    f"the decided specification as declared-open rather than filled in.")
            return "*not settled*", (
                f"Every reading survived: {listed} are all consistent with the waveform the "
                f"designer picked. The observation does not exercise this coordinate, so the "
                f"question is reported open rather than closed by a guess.")
        if str(out).startswith("oracle_"):
            return f"*{out}*", (
                f"The designer was asked and the answer could not be used (`{out[7:]}`). This is "
                f"recorded as a failed query, not as an open question and not as an answer.")
        return f"*{out}*", f"The resolution returned `{out}`."

    rounds = sorted({w.get("round") for w in witnesses if w.get("round")})
    multi = len(rounds) > 1

    # A witness that names no coordinate is not a question.  `contradiction:default` is the
    # deadness certificate -- a context at which the prose as written admits nothing at all --
    # and rendering it through the fork machinery produces the nonsense `None -- which of 0
    # readings of the prose holds`, over the constructors of `KNone`.  It is worth showing, and
    # it gets its own section: it is the *reason* the repair questions exist, not one of them.
    qs = [w for w in witnesses if w.get("choice") or w.get("hole")]
    # And a violation names no coordinate either, for the opposite reason: it is not a question
    # about a place the prose left open, it is a place the prose closed twice.  It has to be kept
    # out of `dead` -- the deadness text says "the specification admits no behaviour at all here",
    # and a violated property is the exact reverse, a behaviour the definitions do admit and the
    # guarantee forbids.  Rendered under that heading it would have read as its own opposite.
    vios = [w for w in witnesses if w.get("kind") == "violation"]
    dead = [w for w in witnesses
            if not (w.get("choice") or w.get("hole") or w.get("kind") == "violation")]
    asked = {(w.get("round"), w.get("choice") or w.get("hole")) for w in qs}

    # A question is a coordinate asked in a round; a witness is one *pair* of its readings, and
    # three readings need three witnesses to tell them apart.  Numbering the witnesses Q1..Q4
    # would put four headings under an opening sentence that says there are two questions, and
    # would give one coordinate three numbers -- a reader counting headings would get a different
    # answer from a reader reading the first line, and a different one again from `REPORT.md`.
    # So the number belongs to the question and the letter to the separation: Q1a, Q1b, Q1c are
    # one question told apart three ways, and Q2 is a question with only one pair to separate.
    groups: dict = {}
    for i, w in enumerate(qs):
        groups.setdefault((w.get("round"), w.get("choice") or w.get("hole")), []).append(i)
    label: dict[int, str] = {}
    for n, members in enumerate(groups.values(), 1):
        for j, i in enumerate(members):
            label[i] = f"Q{n}" + (chr(ord("a") + j) if len(members) > 1 else "")

    def group_of(w: dict) -> list[int]:
        return groups[(w.get("round"), w.get("choice") or w.get("hole"))]

    # Carried into the projection and never put to the designer.  This is not the same list
    # as `deferred` below: a deferred question was never modelled, and one of these was modelled,
    # searched over the whole domain, and found to make no observable difference -- so there is
    # no stimulus to send and nothing a measurement could return.  Without this section the two
    # documents disagree on how many questions the specification raised, because `REPORT.md`
    # counts the open ones and this file would only have counted the answered ones.
    named = {w.get("choice") or w.get("hole") for w in witnesses}
    unasked = [q for q in list(ext.get("choices") or []) + list(ext.get("holes") or [])
               if q.get("name") not in named]

    rcol, rsep = ("round | ", "---|") if multi else ("", "")
    L = [f"# {case_name} — the questions, and what the designer answered", "",
         f"**{len(asked)} question(s).** Each one is a place where this specification's "
         f"prose admits more than one behaviour, found by evaluating the partial semantics over "
         f"the whole context domain rather than by reading the prose again. Under each question "
         f"is the cheapest legal input that tells its readings apart, drawn as a waveform, and "
         f"under that is the waveform the designer picked when shown that input.", ""]
    if len(qs) > len(asked):
        L += [f"They are separated by **{len(qs)} inputs**, because readings are told apart two "
              f"at a time: a question over three readings needs three comparisons, and each one "
              f"gets its own row and its own waveform below, lettered under its question's "
              f"number — Q1a, Q1b. The rows of one question share an answer: the reading the "
              f"designer left standing in all of them.", ""]
    if multi:
        L += [f"They were asked over **{len(rounds)} rounds**. A round answers what it can and "
              f"the next one is posed against the specification the answers leave behind, so a "
              f"question can appear here more than once — asked, narrowed but not settled, and "
              f"asked again against a different option set. Both askings are shown.", ""]
    if vios:
        # Counted apart from the question total and said before the table, because a reader who
        # meets the first violation halfway down the file will have read the opening sentence as
        # a promise that everything below it is a place the prose left open.
        n = len(vios)
        L += [f"A further **{n} finding{'' if n == 1 else 's'}** below {'is' if n == 1 else 'are'}"
              f" not of that kind: {'a property' if n == 1 else 'properties'} the specification "
              f"states about itself that its own definitions break. "
              f"{'It is' if n == 1 else 'They are'} not counted in the question total, because "
              f"{'it is' if n == 1 else 'they are'} not a place the prose is open — "
              f"{'it is' if n == 1 else 'they are'} a place it is closed two ways. See "
              f"[*Where the prose forbids what it defines*](#where-the-prose-forbids-what-it-"
              f"defines), and [`PROPERTIES.md`](PROPERTIES.md) for the full property record.", ""]
    L += ["The argument for each answer — the evidence, and the sentence of the specification it "
          "changes — is in [`REPORT.md`](REPORT.md). This file is the questions.", ""]
    if unasked:
        # `REPORT.md`'s summary counts these in its total, and a reader comparing the two bold
        # numbers should not have to work out that they count different things.
        n = len(unasked)
        L += [f"A further **{n} question{'' if n == 1 else 's'}** the prose raises "
              f"{'is' if n == 1 else 'are'} listed at the foot of this file and never asked: the "
              f"projection proves that no legal context separates their readings, so there is no "
              f"stimulus to send and no answer to record. Counting "
              f"{'it' if n == 1 else 'them'}, the specification raised "
              f"**{len(asked) + n}** questions — the number [`REPORT.md`](REPORT.md) reports.", ""]
    L += [f"| # | {rcol}question | kind | from | options | domain | separating input | answer |",
          f"|---|{rsep}---|---|---|---|---|---|---|"]
    for i, w in enumerate(qs):
        src = choices.get(w.get("choice")) or holes.get(w.get("hole")) or {}
        reads = [lab.split(" = ")[-1] for lab, _ in _bands(w)]
        L.append(f"| {label[i]} | {str(w.get('round')) + ' | ' if multi else ''}"
                 f"`{w.get('choice') or w.get('hole')}` | {w.get('kind')} | "
                 f"{', '.join(_basis_ids(ext, src)) or '—'} | "
                 f"{' / '.join(f'`{r}`' for r in reads)} | "
                 f"{_domain_cell(src, w.get('hole') in holes, len(reads))} | "
                 f"{w.get('cost')} cycle(s){', minimal' if w.get('minimal_in_domain') else ''} | "
                 f"{answer(w)[0]} |")
    L.append("")

    if vios:
        n = len(vios)
        L += ["## Where the prose forbids what it defines", "",
              f"**{n} propert{'y' if n == 1 else 'ies'} the specification states about itself "
              f"{'is' if n == 1 else 'are'} broken by the same specification's definitions.** "
              f"Not an ambiguity: at the context drawn under each one, the sentences that say "
              f"what the design does admit a behaviour that the sentence quoted beside them says "
              f"must never happen. No reading of the prose satisfies both, so there was no menu "
              f"of behaviours to offer — what was put to the designer is the pair of sentences, "
              f"and the question was which one is wrong.", ""]
        for w in vios:
            r = res_of(w) or {}
            prop = w.get("property", "?")
            cert = w.get("certificate") or {}
            L += [f"### `{prop}`"
                  + (f"  *(round {w['round']})*" if multi and w.get("round") else ""), "",
                  "**The guarantee.**", "", f"> {w.get('statement', '')}", ""]
            if w.get("basis"):
                b = w["basis"] if isinstance(w["basis"], str) else ", ".join(w["basis"])
                L += [f"Read out of {b}. Property kind: `{w.get('property_kind')}`.", ""]
            L += [f"**The behaviour that breaks it**, at `{w.get('ctx_lean')}` — "
                  f"{w.get('cost')} cycle(s)"
                  + (", minimal in the domain" if w.get("minimal_in_domain") else "") + ":", "",
                  waveform(w, w.get("admitted")), ""]
            if len(w.get("admits") or []) > 1:
                L += [f"*{len(w['admits'])} behaviours are admitted at this input; the "
                      f"guarantee rejects the one drawn as the measured trace.*", ""]
            L += ["**That this is proved, not inferred:** "
                  + ", ".join(f"`{k}` {'✓' if v else '✗'}" for k, v in cert.items())
                  + " — `violation` is that the guarantee fails somewhere in the domain, "
                    "`witness` is that the context above is one of the places it fails. Both by "
                    "`decide` over the case's own domain.", ""]
            L += [f"**Answer:** {_vio_answer(w, r)}", ""]

    if dead:
        L += ["## Where the prose contradicts itself", "",
              "Not a question — a proof that there is nothing to ask. At each context below the "
              "specification *as written* admits no behaviour at all, so no reading of it is "
              "right and no measurement could confirm one. The repair questions above are what "
              "is asked in its place: not which reading the prose means, but which sentence it "
              "has to give up.", ""]
        for w in dead:
            r = res_of(w) or {}
            L += [f"### `{w.get('id')}`"
                  + (f"  *(round {w['round']})*" if multi and w.get("round") else ""), "",
                  f"`{w.get('ctx_lean')}` — {w.get('cost')} cycle(s)"
                  + (", minimal in the domain" if w.get("minimal_in_domain") else "")
                  + ". Shown this input, the designer picked a waveform the prose forbids "
                    "itself from having:", "",
                  waveform(w, r.get("observed"))]

    for i, w in enumerate(qs):
        src = choices.get(w.get("choice")) or holes.get(w.get("hole")) or {}
        # The pair is in the heading only when the question has more than one: with a single
        # separation it is the whole option set, and the list is already printed below.
        aside = ([" vs ".join(f"`{lab.split(' = ')[-1]}`" for lab, _ in _bands(w))]
                 if len(group_of(w)) > 1 else [])
        if multi and w.get("round"):
            aside.append(f"round {w['round']}")
        L += [f"## {label[i]}. `{w.get('choice') or w.get('hole')}` — {title(w)}"
              + (f"  *({'; '.join(aside)})*" if aside else ""), ""]
        if src.get("why_required"):
            L += [src["why_required"], ""]
        quoted = _quote(ext, src)
        if quoted:
            L += ["**Where the question comes from.** The prose says this and no more:", "",
                  *quoted, ""]
        L += _options(w, src, w.get("hole") in holes)
        cert = w.get("certificate") or {}
        L += ["", "**That this is a real question, not a wording preference:** "
                  + ", ".join(f"`{k}` {'✓' if v else '✗'}" for k, v in cert.items())
                  + f" — proved by `decide` over the case's own domain, at the context drawn "
                    f"below (`{w.get('ctx_lean')}`).", ""]
        r = res_of(w) or {}
        L += [waveform(w, r.get("observed"))]
        verdict, why = answer(w)
        L += [f"**Answer:** {verdict} — {why}", ""]

    # `unasked` is computed with the header, above: its count goes into the opening paragraph so
    # that this file's total and `REPORT.md`'s are visibly the same number.
    if unasked:
        L += ["## Open, and not asked", "",
              "Found in the prose and carried into the projection, but never put to the "
              "designer. At every legal context in the domain the readings agree, so no stimulus "
              "separates them and there is nothing an answer could come back with. They are "
              "gaps in the specification all the same; [`REPORT.md`](REPORT.md) records each one "
              "and why it was left open rather than filled.", ""]
        for q in unasked:
            what = q.get("missing") or "; ".join(c.get("reading", "") for c in
                                                 (q.get("candidates") or []))
            L += [f"* **`{q.get('name')}`** — {what.rstrip('.')}."]
        L.append("")

    deferred = ext.get("deferred") or []
    L += ["## Seen in the prose, outside the model", ""]
    if not deferred:
        L.append("None: every question the extraction found was carried into the projection.")
    else:
        L.append("Visible in the prose, outside what this projection can model. They are named "
                 "rather than dropped, because a question that is not modelled is still a "
                 "question the specification leaves open.")
        L.append("")
        for d in deferred:
            # `question` and `why_deferred` are the keys `schema.validate_extraction` REQUIRES on
            # a deferred entry.  This used to read `what`/`why`/`reason`, which no extraction has
            # ever carried, so every deferred question in the corpus rendered as its name, an
            # em-dash and nothing at all -- the one place a reader is told to look for the
            # coverage the projection gave up, printing the fact that it gave some up and not
            # which.  The old names are still accepted, since nothing checks them either way.
            what = d.get("question") or d.get("what") or d.get("why") or ""
            why = d.get("why_deferred") or d.get("reason") or ""
            frm = ", ".join(f"`{c}`" for c in (d.get("from_clauses") or []))
            L.append(f"* **{d.get('name', d.get('id', '?'))}** — {what.rstrip('.')}."
                     + (f"  Raised by {frm}." if frm else "")
                     + (f"\n\n  *Deferred because:* {why}" if why else ""))
    L.append("")
    return "\n".join(L)


