#!/usr/bin/env python3
"""What comes out: a decided Lean specification with its proofs, a decided prose one, the
question list that both are answers to, and the report that argues for them.

Everything upstream of this module *diagnoses*.  `extraction.json` says where the prose is
open, `Partial.lean` says what the open points mean, stage 3 proves which of them are real, and
stage 6 asks the designer which reading holds.  What none of them produces is a
specification.  Until now the decided reading lived in two places -- a `decisions` list in
`extraction.json`, and a hand-edited `def decidedCfg` in `Partial.lean` -- and the second was
written by the agent, which is exactly the coordinate where a hand edit can quietly say
something the decisions do not.

So `decidedCfg` is *derived* here, and the derivation is total:

    every field of `Cfg` is either named by a decision (`cfg_field` / `cfg_value`)
    or listed in `remaining_open` with a reason.

A field that is neither is a hard error, not a default.  This is the anti-invention rule of
`goal.md` made mechanical: the framework refuses to emit a specification that silently fills a
coordinate nobody decided, and it equally refuses to hide one it left open -- an open field
must be *declared* open, and it then appears under its own heading in `REPORT.md` rather than
disappearing into a default value.

Two Lean files come out, and the pair is deliberate:

  * `DecidedSpec.lean` imports `Partial`, which is how the rest of the pipeline runs it.
  * `DecidedSpec.standalone.lean` is `LeanSpec.lean`, `Partial.lean` and the decided section
    concatenated into one file that elaborates on its own.  "Full content with proof" means a
    file a reader can run without knowing this directory's layout, and a file whose proofs
    depend on two imports the reader has to go and find is not that.

Both are elaborated before they are reported, and the axioms of every theorem are read rather
than the exit code -- an errored tactic leaves a `sorryAx` body behind with no `sorry` in the
source, and a "proved" specification resting on that is worse than none.

Neither of them argues for itself.  The specification is one artifact and the case for it is
another: `QUESTIONS.md` states each question, draws the input that separates its readings, and
gives the designer's answer; `REPORT.md` says what changed in the prose and on whose authority,
and what is still unsaid.  A specification with the argument inlined cannot be read as a
specification, and an argument inlined in a generated file cannot be checked by anything.

Nothing here reads a reference implementation, because there is none: the only authority this
half of leanSilicon has is the designer, and the only thing it can say about the decided
specification is which questions were put and what came back.  A report that quoted an answer
key would be reporting an experiment; this one reports a decision procedure.
"""
from __future__ import annotations

